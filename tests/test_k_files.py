    assert sniff.header_problems(["Homeroom", "Kid", "Dismissal"],
                                 _cols([(s, k, rng.choice(["Bus", "Walker"])) for (k, _), s in
                                        zip(rows, SURNAMES * 5)])) is None
    for header in (["Zelmira", "Kid"], ["Kid", "Zelmira"], ["Buddy", "Kid"]):
        prob = sniff.header_problems(header, _cols(rows))
        assert prob is not None and prob.record_like, header
    src = tmp_path / "in" / "mentors.csv"
    src.parent.mkdir(parents=True)
    src.write_text("Kid,Mentor\n" + "".join(f"{k},{m}\n" for k, m in rows), encoding="utf-8")
