@dataclass
class TextDialect:
    """CSV-family layout needed to mirror the file byte for byte."""

    delimiter: str | None  # None = single-column file
    quotechar: str = '"'
    line_ending: str = "\n"  # '\r\n' | '\n' | '\r'
    line_ending_mixed: bool = False
    trailing_newline: bool = True
    trailing_blank_lines: int = 0
    interior_blank_lines_dropped: int = 0
    quoting: str = "minimal"  # file label: 'minimal' | 'all' | 'strings-only' | 'per-column'
    header_quoted: list[bool] = field(default_factory=list)
    column_quoting: list["ColumnQuoting"] = field(default_factory=list)
    has_header: bool = True
    #: single-column files: candidate delimiters (',', tab, '|', ';') that made the
    #: source quote a value (pandas quotes 'Smith, J' in a one-column file); the
    #: writer quotes values containing them too, so default readers still parse it.
    extra_quote_chars: str = ""
    #: R7-05: the other candidate delimiters (-> their field count) that split every sampled record of the source
    #: consistently too, when the content rules (not the quoting) chose ``delimiter`` (``io.sniff.sniff_delimiter``):
    #: the report flags the layout self-check, which re-reads the output with ``delimiter`` and cannot contradict it.
    delimiter_alternatives: dict[str, int] = field(default_factory=dict)


