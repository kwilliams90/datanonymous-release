LINE_ENDING_NAMES = {"\r\n": "CRLF", "\n": "LF", "\r": "CR"}
PANDAS_COMPRESSION = {"gz": "gzip", "zip": "zip", "bz2": "bz2", "xz": "xz"}
HEADER_FIX = "add a header row (the column names) as the first line of the file"
HEADER_ASSERT_FIX = "; or pass --header-row 1 if the first line already is the header row"


class HeaderLooksLikeData(ReadError):
    """The first line looks like a data record (or prose), not a header row."""

    def __init__(self, problem: sniff.HeaderProblem) -> None:
        super().__init__(problem.text(), fix=HEADER_FIX + (HEADER_ASSERT_FIX if problem.record_like else ""))
        self.problem = problem


def pandas_encoding(layout: FileLayout) -> str:
    """Codec name for pandas that also consumes the BOM."""
    enc = layout.encoding or "utf-8"
    if layout.bom:
        if enc == "utf-8":
            return "utf-8-sig"
        if enc.startswith("utf-16"):
            return "utf-16"
    return enc


def read_source_bytes(path: Path, compression: str | None) -> bytes:
    if compression:
        return compress.read_bytes(path, compression)
    return path.read_bytes()


def parse_text_bytes(data: bytes, encoding: str | None = None, delimiter: str | None = None,
                     check_header: bool = True) -> ReadResult:
    """Parse CSV bytes into a layout and one raw table (no file access).

    ``check_header``: refuse a first line that looks like data
    (:class:`HeaderLooksLikeData`); off when re-reading our own output.
    """
    messages: list[Message] = []
    enc = sniff.sniff_encoding(data, encoding)
    messages.extend(enc.messages)
    text = sniff.decode(data, enc)
    le = sniff.sniff_line_ending(text)
    if le.mixed:
        kinds = ", ".join(f"{LINE_ENDING_NAMES[k]}={v}" for k, v in le.counts.items() if v)
        messages.append(Message("warning", "line_endings_mixed",
                                f"mixed line endings ({kinds}); output uses the majority"))
    dialect = TextDialect(delimiter=None, line_ending=le.line_ending, line_ending_mixed=le.mixed,
                          trailing_newline=le.trailing_newline)
    layout = FileLayout(format="csv", encoding=enc.encoding, bom=enc.bom, encoding_confidence=enc.confidence,
                        text=dialect)
    if text == "":
        dialect.has_header = False
        dialect.trailing_newline = False
        return ReadResult(layout, [RawTable(None, [], [], 0)], messages)

    footer, dinfo, records = _split_footer(text, delimiter)
    if footer is not None:  # K-17: a footer note below the data is layout text, not a record
        text = footer.body
    dialect.delimiter = dinfo.delimiter
    if dinfo.ambiguous:  # R7-05: a guess among consistent candidates, which the self-check cannot contradict
        dialect.delimiter_alternatives = dict(dinfo.alternatives)
        messages.append(ambiguous_delimiter_message(dinfo))
    parse_delim = dinfo.delimiter or sniff.placeholder_delimiter(text)
    if footer is None and records is None and dinfo.delimiter is not None:
        first = sniff._records(text, parse_delim, limit=0, min_records=1)
        if first:
            utf8 = data[len(enc.bom):] if enc.encoding == "utf-8" else None
            arrow = _arrow_records(text, parse_delim, first[0], utf8)
            if arrow is not None and arrow.num_rows > 1:
                from ..profile.codes import register_arrow

                header = first[0]
                body = arrow.slice(1)
                columns = []
                for i, name in enumerate(header):
                    array = body.column(i)
                    values = array.to_numpy(zero_copy_only=False)
                    base = values
                    while isinstance(base, np.ndarray):
                        base.flags.writeable = False
                        base = base.base
                    col = RawColumn(name, values)
                    register_arrow(col.values, array)
                    columns.append(col)
                problem = sniff.header_problems(header, [c.values for c in columns]) if check_header else None
                if problem is not None:
                    raise HeaderLooksLikeData(problem)
                tail = text[len(text.rstrip("\r\n")):]
                dialect.trailing_blank_lines = max(0, len(sniff.LINE_BREAK_RE.findall(tail)) - 1)
                q = sniff.scan_quoting(text, parse_delim, len(header), single_column=False)
                messages.extend(q.messages)
                dialect.header_quoted = q.header_quoted
                dialect.column_quoting = q.columns
                dialect.quoting = q.label
                dialect.extra_quote_chars = q.extra_quote_chars
                layout.extra["_csv_arrow"] = True
                return ReadResult(layout, [RawTable(None, list(header), columns, body.num_rows)], messages)
    if records is None:
        records = _parse_records(text, parse_delim)
    if not records:
        raise ReadError("no records found")

    header = records[0]
    k = len(header)
    if k == 0:
        raise ReadError("the first line (header) is blank", fix="remove leading blank lines")
    body = records[1:]
    # trailing blank lines are reproduced; interior blank lines are dropped (multi-column files)
    trailing = 0
    while body and body[-1] == []:
        body.pop()
        trailing += 1
    if k == 1:
        # in a single-column file a blank line is a blank value; the final line break
        # of the file is already accounted for by trailing_newline.
        body.extend([[]] * trailing)
        trailing = 0
        body = [r if r else [""] for r in body]
    else:
        n_blank = sum(1 for r in body if not r)
        if n_blank:
            body = [r for r in body if r]
            dialect.interior_blank_lines_dropped = n_blank
            messages.append(Message("warning", "blank_lines_dropped",
                                    f"{n_blank} blank line(s) between records were dropped"))
    dialect.trailing_blank_lines = trailing
    table_layout: dict[str, Any] = {}
    if footer is not None:  # the file ends after the footer: its final line break and blank lines are mirrored there
        breaks = len(sniff.LINE_BREAK_RE.findall(footer.tail))
        dialect.trailing_newline = breaks > 0
        dialect.trailing_blank_lines = max(0, breaks - 1)
        table_layout = footer_layout(footer)
        layout.extra["n_footer_lines"] = len(footer.notes)
        messages.append(Message(
            "info", "csv_footer",
            f"{len(footer.notes)} line(s) without a delimiter below the data are a footer note, not data rows: "
            "written in place as same-shape placeholders (--keep-titles: verbatim)"))
    for i, r in enumerate(body):
        if len(r) != k:
            if i > 0 and len(body) - i <= sniff.MAX_FOOTER_LINES:  # K-17: only the last lines break the count
                raise ragged_tail_error(len(body) - i)
            raise ReadError(
                f"record {i + 2} has {len(r)} field(s) but the header has {k}",
                fix="repair the ragged rows, or pass --delimiter if the delimiter was guessed wrong",
            )
    cols = list(zip(*body)) if body else [() for _ in range(k)]
    problem = sniff.header_problems(header, cols) if check_header else None
    if problem is not None:
        raise HeaderLooksLikeData(problem)
    q = sniff.scan_quoting(text, parse_delim, k, single_column=dinfo.delimiter is None)
    messages.extend(q.messages)
    dialect.header_quoted = q.header_quoted
    dialect.column_quoting = q.columns
    dialect.quoting = q.label
    dialect.extra_quote_chars = q.extra_quote_chars
    columns = [RawColumn(header[i], _obj_array(cols[i])) for i in range(k)]
    return ReadResult(layout, [RawTable(None, list(header), columns, len(body), table_layout)], messages)


def _arrow_records(text: str, delimiter: str, header: list[str], utf8: bytes | None = None) -> Any:
    """All-string Arrow table, including the header, or None for the CSV fallback.

    The permissive stdlib parser remains authoritative for irregular layouts.
    Empty physical lines (including inside quoted values), NUL, single columns,
    ragged records and Arrow's block-size/quoting failures take that path.
    """
    import pyarrow as pa
    import pyarrow.csv as pacsv

    k = len(header)
    if k < 2 or "\x00" in text or len(delimiter) != 1 or ord(delimiter) > 127:
        return None
    body = text.rstrip("\r\n")
    if any(mark in body for mark in ("\n\n", "\r\r", "\n\r")):
        return None
    try:
        # Do not strip the tail before parsing: permissive parsers accept an
        # unterminated final quote, whose trailing newlines are field values.
        raw = utf8 if utf8 is not None else text.encode("utf-8")
        table = pacsv.read_csv(
            pa.BufferReader(raw),
            read_options=pacsv.ReadOptions(autogenerate_column_names=True, block_size=1 << 26, use_threads=True),
            parse_options=pacsv.ParseOptions(delimiter=delimiter, quote_char='"', double_quote=True,
                                             escape_char=False, newlines_in_values=True, ignore_empty_lines=False),
            convert_options=pacsv.ConvertOptions(column_types={f"f{i}": pa.string() for i in range(k)},
                                                 null_values=[], strings_can_be_null=False,
                                                 quoted_strings_can_be_null=False, check_utf8=False),
        )
    except (pa.ArrowInvalid, pa.ArrowNotImplementedError, UnicodeError):
        return None
    if table.num_columns != k or not table.num_rows:
        return None
    if [table.column(i)[0].as_py() for i in range(k)] != header:
        return None
    if table.column(k - 1)[-1].as_py().endswith(("\r", "\n")):
        return None
    tail = text[len(body):]
    trailing = max(0, len(sniff.LINE_BREAK_RE.findall(tail)) - 1)
    if trailing:
        if table.num_rows <= trailing:
            return None
        # Arrow emits all-empty fields for physical blank lines; csv.reader
        # emits []. These are layout-only trailing lines in multi-column CSV.
        for column in table.columns:
            if any(column.slice(table.num_rows - trailing).to_pylist()):
                return None
        table = table.slice(0, table.num_rows - trailing)
    return table


def _parse_records(text: str, delimiter: str) -> list[list[str]]:
    reader = csv.reader(io.StringIO(text, newline=""), delimiter=delimiter, quotechar='"', doublequote=True,
                        strict=False, skipinitialspace=False)
    try:
        return list(reader)
    except csv.Error:  # the tool's own words: the parser's message is never printed (R7-04)
        raise ReadError(f"CSV parse error on line {getattr(reader, 'line_num', '?')}",
                        fix="check --delimiter / --encoding") from None


def _split_footer(text: str, delimiter: str | None
                  ) -> tuple[sniff.FooterCandidate | None, sniff.DelimiterInfo, list[list[str]] | None]:
    """(the footer block or None, the delimiter, the parsed records above the footer or None) of ``text`` (K-17).

    A :func:`~.sniff.footer_candidate` is a footer only when the text above it has a delimiter of its own
    (sniffed without the notes: a header of two or more fields) and the whole file, parsed with that delimiter,
    ends with exactly the notes, each a record of its own (a note holds no quote character, so its fields are its
    text split at the delimiter: a note is never the inside of a quoted multi-line value). A note that holds the
    delimiter (as text punctuation, whatever number of pieces it makes: ``Monday, October 3, 2025``) is a note only
    when no field of the records starts with a space (:func:`_space_led`: in ``a, b`` files, or with values that
    start with a space, such a line may be a record). Otherwise the whole text is sniffed and parsed as before: a
    ragged last line FAILs the file (:func:`ragged_tail_error`)."""
    cand = sniff.footer_candidate(text, delimiter)
    if cand is not None:
        try:
            dinfo: sniff.DelimiterInfo | None = sniff.sniff_delimiter(cand.body, delimiter)
        except ReadError:
            dinfo = None
        if dinfo is not None and dinfo.delimiter is not None:
            d = dinfo.delimiter
            try:
                records = _parse_records(text, d)
            except ReadError:
                records = []
            # from the end: blank lines, then the notes as records of their own (blank lines between them), then
            # the blank lines above them; what is left is the body
            notes = [n.split(d) for n in reversed(cand.notes)]
            j, matched = len(records), 0
            while j > 0 and matched < len(notes):
                if records[j - 1] == []:
                    j -= 1
                elif records[j - 1] == notes[matched]:
                    j, matched = j - 1, matched + 1
                else:
                    break
            while j > 0 and records[j - 1] == []:
                j -= 1
            k = len(records[0]) if records else 0
            if matched == len(notes) and j > 1 and k >= 2 and not (
                    any(len(n) > 1 for n in notes)
                    and _space_led(records, j)):
                return cand, dinfo, records[:j]
    try:
        return None, sniff.sniff_delimiter(text, delimiter), None
    except ReadError as exc:
        tail = _ragged_tail(text, delimiter)
        if tail is None:
            raise
        raise ragged_tail_error(tail) from exc


def _space_led(records: list[list[str]], end: int) -> bool:
    """K-17: a field after the first of a record above the footer (``records[1:end]``) starts with a space: the
    delimiter is followed by a space in the data too (``a, b`` files, values with a leading space), so a last line
    that holds it followed by a space may be a record, and is no note."""
    return any(f[:1] == " " for r in itertools.islice(records, 1, end) for f in r[1:])


def _ragged_tail(text: str, delimiter: str | None) -> int | None:
    """K-17: the number (1-3) of last non-blank lines without which a text that splits inconsistently splits
    consistently (with a delimiter, into the header and at least one record), else None: a note below the data that
    is no footer note (a digit-only line, a quote, an unspaced delimiter) or a record cut short."""
    for m in range(1, sniff.MAX_FOOTER_LINES + 1):
        cut = sniff.drop_last_lines(text, m)
        if cut is None:
            return None
        try:
            info = sniff.sniff_delimiter(cut, delimiter)
        except ReadError:
            continue
        if info.delimiter is not None and len([r for r in _parse_records(cut, info.delimiter) if r]) >= 2:
            return m
    return None


def ragged_tail_error(m: int) -> ReadError:
    """The error of a file whose field count breaks only in its last ``m`` non-blank lines (K-17). Counts only: the
    lines are never printed."""
    return ReadError(
        f"only the last {m} non-blank line(s) of the file break the number of fields of the records above them, "
        "and they are no footer note (a note below the data holds a letter or is a rule of symbols, holds no quote "
        "character, and uses the delimiter only as text punctuation followed by a space)",
        fix="remove the line(s) below the data or repair a record cut short; pass --delimiter if the delimiter was "
            "guessed wrong",
    )


def footer_layout(footer: sniff.FooterCandidate) -> dict[str, Any]:
    """The table layout of a CSV footer block (K-17), as Excel keeps footer rows: ``footer_lines`` (public: the
    positions of the note lines in the block below the data, 1 = the line after the last record; a missing
    position is a blank line) and ``_footer_rows`` (PRIVATE: ``(position, {1: note})``, real text read by the run's
    real-text registry, the leak scan and, with ``--keep-titles``, the D34 screen: ``privacy.texts.layout_texts``)."""
    rows = [(pos, {1: line}) for pos, line in enumerate(footer.lines, 1) if line]
    return {"footer_lines": [pos for pos, _ in rows], "_footer_rows": rows}


def ambiguous_delimiter_message(dinfo: sniff.DelimiterInfo) -> Message:
    """The ``delimiter_ambiguous`` warning (R7-05): which candidates split every sampled line consistently, which
    one was used and why, with the ``--delimiter`` fix (characters and column counts only, never a value)."""
    name = sniff.delimiter_name
    chosen = dinfo.delimiter or ","
    runner = next(iter(dinfo.alternatives))
    others = " and the ".join(f"{name(d)} ({n} columns)" for d, n in dinfo.alternatives.items())
    if dinfo.method == "punctuation":
        why = f"the {name(runner)} is followed by a space at most of its places, like punctuation in text"
    else:
        why = (f"nothing else told them apart, and a {name(runner)} is more common inside text (names, numbers, "
               f"prose) than a {name(chosen)}")
    return Message(
        "warning", "delimiter_ambiguous",
        f"ambiguous delimiter: the {name(chosen)} ({dinfo.n_fields} columns) and the {others} each split every "
        f"sampled line into the same number of fields; the file was read with the {name(chosen)} because {why}. "
        "The layout self-check re-reads the output with the same delimiter, so it cannot tell whether the columns "
        "are right",
        fix=f"check the columns in the report, then pass --delimiter {name(chosen)} to confirm them, or "
            f"--delimiter {name(runner)} to split at the {name(runner)} instead")


def _obj_array(values: tuple[str, ...] | list[str]) -> np.ndarray:
    arr = np.empty(len(values), dtype=object)
    arr[:] = list(values)
    return arr


def read(req: "ReadRequest") -> ReadResult:
    """Registry reader for the ``csv`` format."""
    data = read_source_bytes(req.path, req.compression)
    try:
        # --header-row 1 asserts that the first line is the header row (as for Excel): no plausibility check
        result = parse_text_bytes(data, req.settings.encoding, req.settings.delimiter,
                                  check_header=req.purpose != "selfcheck" and req.settings.header_row != 1)
    except HeaderLooksLikeData as e:
        if e.problem.prose and req.rel_path.lower().endswith(".txt"):
            raise NotTabular("not a table: a text file whose first line reads like a sentence (prose)") from None
        raise
    result.layout.compression = req.compression
    if req.compression:  # container details (gzip header, zip member) mirrored by compress.write_bytes
        result.layout.extra.update(compress.container_layout(req.path, req.compression))
        if req.purpose == "source":  # a stored name is free text: never copied (AREA F)
            result.messages.extend(compress.container_messages(result.layout.extra))
    if req.settings.header_row not in (None, 1):
        result.messages.append(Message("warning", "header_row_ignored",
                                       "--header-row applies to Excel files; ignored for this text file"))
    return result


# --------------------------------------------------------------------------- writing
def _quote(v: str, q: str) -> str:
    return q + v.replace(q, q + q) + q


def render_column(values: np.ndarray, cq: ColumnQuoting, delimiter: str, q: str, extra: str = "") -> list[str]:
    """Apply the column's quoting policy to rendered values (None -> '').

    ``extra``: further characters that force quoting (single-column files).
    With ``cq.bare_quotes`` a quote character only forces quoting at the start
    of a value (the source wrote ``5'10"`` unquoted).
    """
    import pyarrow as pa
    import pyarrow.compute as pc

    empty = q + q if cq.quote_empty else ""
    vals = values.tolist()
    if cq.policy == "always":
        return [_quote(v, q) if v else empty for v in vals]
    arr = pa.array(vals, type=pa.string())
    chars = delimiter + extra + ("" if cq.bare_quotes else q)
    special = "[" + "".join("\\" + ch if ch in "\\]^-" else ch for ch in chars) + "\r\n]"
    if cq.bare_quotes:
        special += "|^" + ("\\" + q if q in "\\.^$|?*+()[]{}" else q)
    quote = pc.fill_null(pc.match_substring_regex(arr, special), False)
    if cq.policy == "nonnumeric":
        numeric = pc.fill_null(pc.match_substring_regex(arr, "^" + sniff.NUMERIC_RE.pattern + "$"), False)
        quote = pc.or_(quote, pc.invert(numeric))
    need = np.asarray(quote.to_numpy(zero_copy_only=False), dtype=bool)
    out = ["" if v is None else v for v in vals]
    for i in np.flatnonzero(need).tolist():
        if out[i]:
            out[i] = _quote(out[i], q)
    if empty:
        out = [v if v else empty for v in out]
    return out


def _write_delimiter(t: TextDialect) -> str:
    """The delimiter values are quoted for (a one-column source has none: a character no value holds)."""
    return t.delimiter if t.delimiter is not None else "\x00"


def column_text(values: np.ndarray, cq: ColumnQuoting, t: TextDialect) -> list[str]:
    """One column's values as the writer renders them under the quoting ``cq`` in the dialect ``t``."""
    return render_column(values, cq, _write_delimiter(t), t.quotechar, t.extra_quote_chars)


def written_dialect(t: TextDialect, header: list[str], columns: list[np.ndarray],
                    source_index: list[int]) -> TextDialect:
    """The dialect the writer gives one table: the source's, except what the written table cannot carry.

    Used by :func:`write` and by the self-check, so the output is compared with what it can show (R6-06). A
    table written with ONE column (``--exclude`` leaving one column of a wider file, or a one-column source)
    has no delimiter on any line, and every line after its header is a value:

    * trailing blank lines would read back as blank values: none are written;
    * a blank value at the end of a file without a final line break would be lost: :func:`serialize` moves it
      up, and when every value is blank (nothing to swap with) the file ends with a line break;
    * a blank header would read back as a blank first line (no header row): it is quoted.

    Its delimiter cannot be seen: values holding the source's delimiter are still quoted for it, and the
    self-check re-reads the output with the source's delimiter. ``header_quoted``/``column_quoting`` stay
    indexed by source column (``source_index``). Any other table gets ``t`` itself.
    """
    if len(header) != 1 or not t.has_header:
        return t
    i = source_index[0]
    hq = list(t.header_quoted)
    if header[0] == "":
        hq += [False] * (i + 1 - len(hq))
        hq[i] = True
    cq = t.column_quoting[i] if i < len(t.column_quoting) else ColumnQuoting()
    vals = columns[0].tolist() if columns else []
    all_blank = bool(vals) and not cq.quote_empty and all(v is None or v == "" for v in vals)
    return dataclasses.replace(t, trailing_blank_lines=0, trailing_newline=t.trailing_newline or all_blank,
                               header_quoted=hq, column_quoting=list(t.column_quoting))


def serialize(layout: FileLayout, header: list[str], columns: list[np.ndarray],
              quoting: list[ColumnQuoting], header_quoted: list[bool], footer: list[str] | None = None) -> bytes:
    """Serialise one table to bytes mirroring ``layout`` (no compression). ``footer``: the lines written below the
    data (K-17: blank lines and the footer notes' placeholders, :func:`footer_text`)."""
    t = layout.text
    assert t is not None
    q = t.quotechar
    if not t.has_header and not header:
        text = ""
    else:
        d = t.delimiter if t.delimiter is not None else ""
        wd = _write_delimiter(t)
        extra = t.extra_quote_chars
        hfields = [
            _quote(h, q) if (hq or sniff.needs_quoting(h, wd, q, extra)) else h
            for h, hq in zip(header, header_quoted + [False] * (len(header) - len(header_quoted)))
        ]
        lines = [d.join(hfields)]
        if columns and len(columns[0]):
            rendered = [column_text(c, cq, t) for c, cq in zip(columns, quoting)]
            if len(rendered) == 1:
                vals = rendered[0]
                if not t.trailing_newline and vals[-1] == "":
                    # a final blank line would read back as a line break: move the blank up
                    j = next((i for i in range(len(vals) - 1, -1, -1) if vals[i] != ""), None)
                    if j is not None:
                        vals[j], vals[-1] = vals[-1], vals[j]
                lines.extend(vals)
            else:
                lines.extend(_join_rows(rendered, d))
        lines.extend(footer or ())
        le = t.line_ending
        text = le.join(lines)
        if t.trailing_newline:
            text += le
        text += le * t.trailing_blank_lines
    codec = layout.encoding or "utf-8"
    try:
        return layout.bom + text.encode(codec)
    except UnicodeEncodeError as e:
        raise WriteError(f"a synthetic value cannot be encoded as {codec}: {e.reason}",
                         fix="pass --encoding utf-8 or report this as a bug") from None


def _join_rows(rendered: list[list[str]], delimiter: str) -> list[str]:
    """Join already quoted fields in native code, retaining zip's shortest-column rule."""
    import pyarrow as pa
    import pyarrow.compute as pc

    n = min(map(len, rendered))
    arrays = [pa.array(col[:n], type=pa.large_string()) for col in rendered]
    return pc.binary_join_element_wise(*arrays, pa.scalar(delimiter, type=pa.large_string())).to_pylist()


def write(req: "WriteRequest") -> None:
    """Registry writer for the ``csv`` format (one table)."""
    layout = req.layout
    if layout.text is None or len(req.tables) != 1:
        raise WriteError("CSV writer needs exactly one table and a text layout")
    table = req.tables[0]
    t = written_dialect(layout.text, table.header, table.columns, table.source_index)
    if t is not layout.text:
        layout = dataclasses.replace(layout, text=t)
    quoting = [t.column_quoting[i] if i < len(t.column_quoting) else ColumnQuoting() for i in table.source_index]
    hq = [t.header_quoted[i] if i < len(t.header_quoted) else False for i in table.source_index]
    data = serialize(layout, table.header, table.columns, quoting, hq, footer_text(table, req))
    if layout.compression:
        compress.write_bytes(req.path, data, layout.compression, layout)
    else:
        req.path.write_bytes(data)


def footer_text(table: Any, req: "WriteRequest") -> list[str]:  # noqa: ANN401 - a registry.OutTable
    """The lines written below the data of ``table`` (K-17): the source's footer block (``_footer_rows``,
    :func:`footer_layout`) with each note as a same-shape placeholder (``io.excel_write.Placeholders``: the shared
    embedded-PII rules, never a real text, phone number or SSN of the run, R8-04) or verbatim with
    ``--keep-titles``, as Excel footer rows are; a "Total"-vocabulary label stays. A table written with one column
    (``--exclude``) gets none: without a delimiter a note would read back as one more value."""
    rows = (table.layout or {}).get("_footer_rows") or []
    if not rows or len(table.header) < 2:
        return []
    from .excel_write import _KEEP_LABEL_RE, Placeholders

    rng = req.rng_for("csv-footer") if req.rng_for else np.random.default_rng(req.seed)
    ph = Placeholders(rng, bool(getattr(req.settings, "keep_titles", False)))
    block = [""] * max(pos for pos, _ in rows)
    for pos, cells in rows:
        note = cells.get(1, "")
        block[pos - 1] = note if _KEEP_LABEL_RE.match(note) else ph.text(note)
    return block


# --------------------------------------------------------------------------- self-check helpers
def layout_diff(source: FileLayout, output: FileLayout, source_tables: list[dict[str, Any]] | None = None,
                output_tables: list[RawTable] | None = None) -> list[str]:
    """CSV dialect differences (column quoting compared by the generic self-check).

    ``source`` is the dialect the written table can carry (the self-check passes
    :func:`written_dialect` of the source). A one-column output re-read without
    the source's delimiter shows none: that is no difference (R6-06).
    """
    issues: list[str] = []
    s, o = source.text, output.text
    if s is None or o is None:
        return ["text dialect missing"]
    one_column = bool(output_tables) and all(len(t.header) <= 1 for t in output_tables or [])
    for name in ("delimiter", "quotechar", "line_ending", "trailing_newline", "trailing_blank_lines", "has_header"):
        if name == "delimiter" and one_column and o.delimiter is None:
            continue
        if getattr(s, name) != getattr(o, name):
            issues.append(f"{name}: source {getattr(s, name)!r}, output {getattr(o, name)!r}")
    if not one_column:  # K-17: the footer notes below the data, by position (a one-column output writes none)
        s_foot = [(tl or {}).get("footer_lines") or [] for tl in source_tables or []]
        o_foot = [(getattr(ot, "layout", None) or {}).get("footer_lines") or [] for ot in output_tables or []]
        if source_tables is not None and output_tables is not None and s_foot != o_foot:
            issues.append(f"footer lines below the data: source {s_foot!r}, output {o_foot!r}")
    issues.extend(compress.container_diff(source, output))  # zip member name, gzip header ... (AREA F)
    return issues


def inferred_dtypes(path: Path, layout: FileLayout, table: str | None = None) -> list[str] | None:
    """dtypes pandas infers with default ``read_csv`` (None if it cannot read the file).

    A single-column file is read with pandas' default separator (``,``), as a
    user would read it, so a value that breaks default parsing shows up as None.
    """
    if layout.text is None or not layout.text.has_header:
        return None
    import pandas as pd

    if _plain_dtype_layout(layout):
        try:
            fast = _inferred_dtypes_arrow(path, layout)
            if fast is not None:
                return fast
        except Exception:
            # This report-only optimization must never prevent the original
            # pandas read, including for codecs/parser options Arrow declines.
            pass
    sep = layout.text.delimiter or ","
    compression = PANDAS_COMPRESSION.get(layout.compression) if layout.compression else None
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            df = pd.read_csv(path, sep=sep, encoding=pandas_encoding(layout), low_memory=False,
                             compression=compression)
    except Exception:
        return None
    return [str(t) for t in df.dtypes]


def _plain_dtype_layout(layout: FileLayout) -> bool:
    t = layout.text
    return bool(t is not None and layout.extra.get("_csv_arrow") and t.delimiter is not None
                and not layout.extra.get("n_footer_lines") and not t.interior_blank_lines_dropped
                and not t.delimiter_alternatives and not t.line_ending_mixed
                and not any(c.bare_quotes for c in t.column_quoting) and layout.encoding_confidence != "low")


# Compress only ordinary, safely bounded decimal numbers. Exponents, long
# integers (including uint64 boundaries), unusual spellings and every NA/bool
# token stay in the witness set for pandas itself to decide.
_WITNESS_NUMBER = re.compile(r"[+-]?(?:[0-9]{1,18}|[0-9]{1,15}\.[0-9]{0,15}|\.[0-9]{1,15})\Z")
_POSSIBLE_NUMBER = re.compile(r"[0-9+\-.eE\s]*\Z")


def _dtype_witnesses(values: list[str]) -> list[str]:
    other: list[str] = []
    ordinary: list[str] = []
    for value in values:
        if _WITNESS_NUMBER.fullmatch(value) and ("." not in value or sum(c.isdigit() for c in value) <= 15):
            ordinary.append(value)
        else:
            other.append(value)
    if ordinary:
        other.extend((ordinary[0], min(ordinary, key=float), max(ordinary, key=float),
                      min(ordinary, key=len), max(ordinary, key=len)))
        for predicate in (lambda s: s.startswith("-"), lambda s: "." in s):
            match = next((s for s in ordinary if predicate(s)), None)
            if match is not None:
                other.append(match)
    # pandas stops a conversion attempt at its first error. In particular an
    # overflowing integer before a decimal can infer differently from the same
    # values in reverse order. Retain witnesses in their original order.
    selected = set(other)
    return list(dict.fromkeys(v for v in values if v in selected))


def _dtype_from_distinct(values: list[str]) -> str:
    """Ask the same pandas C parser about a smaller, dtype-equivalent value set."""
    import pandas as pd
    from pandas._libs.parsers import STR_NA_VALUES

    # A certain text value prevents numeric/bool inference. Keep that actual
    # value so pandas' configured string dtype (str/object) is respected.
    for value in values:
        folded = value.strip().casefold()
        if (not _POSSIBLE_NUMBER.fullmatch(value) and value not in STR_NA_VALUES
                and folded not in {"true", "false"} and "inf" not in folded and "nan" not in folded):
            witnesses = [value]
            break
    else:
        witnesses = _dtype_witnesses(values)
    text = "v,x\n" + "".join(_quote(v, '"') + ",0\n" for v in witnesses)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        frame = pd.read_csv(io.StringIO(text), sep=",", low_memory=False)
    return str(frame.dtypes.iloc[0])


def _inferred_dtypes_arrow(path: Path, layout: FileLayout) -> list[str] | None:
    """Re-read bytes on disk and infer from Arrow distinct values; retain no file cache."""
    import pyarrow.compute as pc

    assert layout.text is not None and layout.text.delimiter is not None
    data = read_source_bytes(path, layout.compression)
    enc = sniff.sniff_encoding(data, pandas_encoding(layout))
    text = sniff.decode(data, enc)
    first = sniff._records(text, layout.text.delimiter, limit=0, min_records=1)
    if not first:
        return None
    utf8 = data[len(enc.bom):] if enc.encoding == "utf-8" else None
    table = _arrow_records(text, layout.text.delimiter, first[0], utf8)
    if table is None or table.num_rows <= 1:
        return None
    return [_dtype_from_distinct(pc.unique(c).to_pylist()) for c in table.slice(1).columns]
