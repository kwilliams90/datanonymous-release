"""Known issues, cluster files (G5: no crash or false FAIL on realistic school files): K-14, K-15, K-17, K-20.

* K-14: an xlsx whose date cells are ISO 8601 text (``t="d"``) with the General number format FAILed the layout
  self-check: openpyxl stamps its default date format on a date assigned to a General cell, and a serial number in
  General reads back as a number. A date cell can hold a format that is no date format only as ISO text, so the
  writer keeps the source format and writes such a cell as ISO text too (``io.excel_write.set_value``; every cell
  path: the data columns' reused cells, header, title and footer cells).
* K-15: an all-text list whose header uses an everyday word missing from the vocabulary (``Homeroom,Kid,Dismissal``,
  ``House,Kid,Assigned``, ``Buddy,Mentor,House``) over name-like values FAILed as headerless. A header cell that is a
  known word naming nobody (a column-name or everyday word on no given-name or surname list), occurring nowhere in
  its column, over a column of known people's names holding no such word, is no value of a record: it is not
  suspect and it vouches for the line (``io.sniff._heads_names``). A rare name is on no word list, a known name is
  on the name lists, so genuine headerless lists are still refused. Hardening: such a word is no value of a column
  of names on no list either (``_heads_column``: K15-A2, names of Somali or Nigerian students), but it vouches for
  other cells only over known names, and never for a line whose ID looks like one more ID of its column (a record's
  placeholder teacher ``TBD`` would copy the student's ID and name as column names, G1). K15-ATK-2: a cell whose
  number of words no value of its column has (``Recipient``, ``Nominee``, ``Rider`` over 10 or more full names; a
  column-name phrase with no name word, ``Absent Teacher``, over one-word surnames) is no value of that column
  (``_foreign_word_count``: a word pattern, no word list), unless another cell of the line is a value of its column
  or one more ID, code or number of it (``_record_cell``: then the line is a record). Header words on no vocabulary
  list or on a name list over names of the same number of words (``Reader,Listener`` over given names) stay
  refused, like the rare names they cannot be told from (the fail-safe residual, fixed by ``--header-row 1``).
* K-17: a CSV with a footer note (``Report generated by Skyward on ...``) FAILed. The last 1-3 non-blank lines of a
  multi-column text that are notes (a letter or a rule of symbols, no quote, the delimiter only as text punctuation
  followed by a space while no field of the records starts with a space: K17-A2, ``Monday, October 3, 2025`` and
  ``-----``; whole records of the parsed file) are a footer block: layout text mirrored like Excel footer rows
  (same-shape placeholders under the shared PII and registry rules, verbatim only with ``--keep-titles``, then
  screened by D34 as titles are), and N data rows in = N out. The documented read code stops after the data rows
  (K17-A1: readr ``n_max``, pandas ``nrows``); other ragged last lines FAIL with a message that names them.
* K-20: a Parquet double column with +inf/-inf FAILed: the values were text tokens and got pseudonyms no double
  holds. Non-finite numbers a column stores natively (Arrow floats, JSON ``Infinity``) are numbers: like ``NaN``
  they are kept verbatim at their exact counts and left out of the statistics (``model.numeric_specials``).
"""

