@dataclass
class QuotingInfo:
    header_quoted: list[bool]
    columns: list[ColumnQuoting]
    label: str
    messages: list[Message] = field(default_factory=list)
    extra_quote_chars: str = ""


def _scan_records(text: str, delimiter: str, q: str, limit_records: int | None = None,
                  limit_chars: int | None = None,
                  min_records: int = MIN_SAMPLE_RECORDS) -> list[list[tuple[str, bool]]]:
    """Tokenise ``text`` into records of (value, was_quoted). Stops on malformed input.

    ``limit_chars``: stop after the record that ends at or beyond this offset, once ``min_records`` records
    are read (every record returned is complete, however long: R2-17)."""
    records: list[list[tuple[str, bool]]] = []
    n = len(text)
    pos = 0
    qq = q + q
    stop = re.compile("[" + re.escape(delimiter) + "\r\n]")

    def field_end(p: int) -> int:
        m = stop.search(text, p)
        return m.start() if m else n
    while pos < n:
        rec: list[tuple[str, bool]] = []
        while True:
            if pos < n and text[pos] == q:
                end = pos + 1
                buf = []
                while True:
                    j = text.find(q, end)
                    if j < 0:
                        return records  # unterminated quote: stop scanning
                    buf.append(text[end:j])
                    if text.startswith(qq, j):
                        buf.append(q)
                        end = j + 2
                        continue
                    pos = j + 1
                    break
                rec.append(("".join(buf), True))
                # anything after the closing quote up to the delimiter is irregular
                pos = field_end(pos)
            else:
                start = pos
                pos = field_end(pos)
                rec.append((text[start:pos], False))
            if pos < n and text[pos] == delimiter:
                pos += 1
                continue
            break
        if pos < n and text[pos] == "\r":
            pos += 1
        if pos < n and text[pos] == "\n":
            pos += 1
        records.append(rec)
        if limit_records is not None and len(records) >= limit_records:
            break
        if limit_chars is not None and pos >= limit_chars and len(records) >= min_records:
            break
    return records


def needs_quoting(value: str, delimiter: str, q: str, extra: str = "") -> bool:
    return (delimiter in value or q in value or "\r" in value or "\n" in value
            or any(c in value for c in extra))


def single_column_quote_chars(records: list[list[tuple[str, bool]]], quotechar: str = '"') -> str:
    """Candidate delimiters that only ever appear inside quoted values of a single-column file."""
    quoted_has: set[str] = set()
    bare_has: set[str] = set()
    for rec in records:
        for val, quoted in rec:
            for c in CANDIDATE_DELIMITERS:
                if c in val:
                    (quoted_has if quoted else bare_has).add(c)
    return "".join(c for c in CANDIDATE_DELIMITERS if c in quoted_has and c not in bare_has)


def scan_quoting(text: str, delimiter: str, n_columns: int, quotechar: str = '"',
                 single_column: bool = False) -> QuotingInfo:
    """Detect header quoting flags and a per-column quoting policy.

    ``single_column``: ``delimiter`` is a placeholder; the candidate delimiters
    found only inside quoted values become ``QuotingInfo.extra_quote_chars``.
    """
    if quotechar not in text:
        cols = [ColumnQuoting("minimal", False) for _ in range(n_columns)]
        return QuotingInfo([False] * n_columns, cols, "minimal")
    records = _scan_records(text, delimiter, quotechar, limit_chars=QUOTE_SCAN_CHARS)
    records = [r for r in records if not (len(r) == 1 and r[0] == ("", False) and n_columns > 1)]
    extra = single_column_quote_chars(records, quotechar) if single_column else ""
    messages: list[Message] = []
    header = records[0] if records else []
    header_quoted = [bool(f[1]) for f in header][:n_columns]
    header_quoted += [False] * (n_columns - len(header_quoted))
    stats = [dict(q_ne=0, u_ne=0, q_empty=0, u_empty=0, q_unneeded=0, q_numeric=0, u_nonnum=0, u_quote=0)
             for _ in range(n_columns)]
    for rec in records[1:]:
        if len(rec) != n_columns:
            continue
        for i, (val, quoted) in enumerate(rec):
            st = stats[i]
            if val == "":
                st["q_empty" if quoted else "u_empty"] += 1
                continue
            num = bool(NUMERIC_RE.fullmatch(val))
            if quoted:
                st["q_ne"] += 1
                if not needs_quoting(val, delimiter, quotechar, extra):
                    st["q_unneeded"] += 1
                if num:
                    st["q_numeric"] += 1
            else:
                st["u_ne"] += 1
                if quotechar in val:
                    st["u_quote"] += 1
                if not num:
                    st["u_nonnum"] += 1
    decided: list[str | None] = []
    for i, st in enumerate(stats):
        if st["q_ne"] and not st["u_ne"]:
            # every value quoted: 'always', unless every quoted value needed quotes anyway (ambiguous)
            decided.append("always" if st["q_unneeded"] else None)
        elif not st["q_unneeded"]:
            decided.append("minimal")
        elif st["q_numeric"] == 0 and st["u_nonnum"] == 0:
            decided.append("nonnumeric")
        else:
            decided.append("minimal")
            messages.append(Message("warning", "quoting_inconsistent",
                                    f"column {i + 1} mixes quoted and unquoted values; output uses minimal quoting"))
    header_extra = any(hq and not needs_quoting(v, delimiter, quotechar, extra)
                       for hq, (v, _) in zip(header_quoted, header))
    file_always = header_extra or "always" in decided
    cols: list[ColumnQuoting] = []
    for i, st in enumerate(stats):
        policy = decided[i] or ("always" if file_always else "minimal")
        if st["q_empty"] and st["u_empty"]:
            messages.append(Message("warning", "quoting_inconsistent",
                                    f"column {i + 1} has both quoted and unquoted empty values"))
        if policy == "minimal" and st["q_empty"] and not st["u_empty"]:
            quote_empty = True
        else:
            quote_empty = st["q_empty"] > st["u_empty"]
        cols.append(ColumnQuoting(policy, quote_empty, bare_quotes=st["u_quote"] > 0))
    policies = {c.policy for c in cols}
    if policies == {"always"} and all(header_quoted):
        label = "all"
    elif policies == {"minimal"} and not any(
        hq and not needs_quoting(v, delimiter, quotechar, extra) for hq, (v, _) in zip(header_quoted, header)
    ):
        label = "minimal"
    elif any(st["q_ne"] for st in stats) and all(st["q_numeric"] == 0 and st["u_nonnum"] == 0 for st in stats):
        label = "strings-only"
    else:
        label = "per-column"
    return QuotingInfo(header_quoted, cols, label, messages, extra)


