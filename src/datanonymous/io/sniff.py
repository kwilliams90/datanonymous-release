"""Text-file sniffers: encoding, line ending, delimiter and quoting (FOUNDATION).

All sniffing works on raw bytes / exactly decoded text (never pandas):

* encoding: BOM from raw bytes (UTF-8, UTF-16 LE/BE); otherwise strict UTF-8,
  then strict cp1252, then latin-1 with a low-confidence warning (design 6).
* line ending: CRLF vs LF vs CR counted on the decoded text (equivalent to raw
  bytes for 8-bit codecs, correct for UTF-16); majority wins, mixed warns.
* delimiter (:func:`sniff_delimiter`, R7-05): every candidate (``,`` tab ``|``
  ``;``) is tried on the first complete records of ~64 KB as ``csv.reader``
  parses the whole text (never fewer than the header and two data records,
  however long: R2-17; no record is cut off at the sample boundary). A
  candidate is *consistent* when it splits every sampled record into the same
  number (>= 2) of fields. One consistent candidate is the delimiter. When
  several are, each rival's character must sit inside the fields of the
  chosen split, and the evidence decides in this order: (1) quoting - a quote
  encloses a whole field, so a split that leaves quote characters inside
  fields cut a quoted value apart; (2) punctuation - a character followed by
  a space at most of its occurrences is text (``Smith, Jane``), not a field
  separator; (3) text-likeness - a comma is the most common of them inside
  names, numbers and prose, then ``;``, then ``|``, then tab, so the least
  text-like candidate splits and the others are read as text. Unless the
  quoting decided, the file gets a ``delimiter_ambiguous`` warning naming the
  candidates (characters and column counts only) with the ``--delimiter``
  fix: the self-check re-reads the output with the same delimiter, so it can
  never contradict the guess. No consistent candidate: single column (only
  when the header has no candidate delimiter at all, otherwise the file
  fails).
* quoting: our own scan of quoted/unquoted fields per column (Sniffer cannot),
  including bare quote characters inside unquoted fields and, for single-column
  files, the candidate delimiters that made the source quote a value.
* header plausibility (:func:`header_problems`): a first line that looks like a
  data record (an e-mail, SSN, phone, web or IP address, ZIP+4, street address
  or date shape, a long or zero-padded number, cells equal to values of their
  own column, or :func:`record_like_cells`: a cell that is no recognisable
  column name and looks like one more value of its column - a name over names
  in any letter case, an ID over IDs, text over text - while no other cell is
  a recognisable column name over numbers, dates, codes or e-mails: a
  headerless list of names, R1-06/R2-05) or, in a single-column file, like
  prose. The reader then refuses the file instead of copying the line verbatim
  as a header. Reasons name columns by position, never values. K-15: a cell
  that is a known word naming nobody (a column-name or everyday word on no
  given-name or surname list: ``Kid``, ``Mentor``) and occurs nowhere in its
  column of names (that holds no such word) is no value of a record: it is not
  suspect (:func:`_heads_column`), and over known people's names it vouches
  for the line (:func:`_heads_names`), unless the line also
  holds a cell that looks like one more ID or code of its column (such a word
  may be a record's placeholder: ``S1000,Okonkwo,Chidi,TBD``). K15-ATK-2: a
  cell whose number of words no value of its column has (one word over full
  names: ``Recipient``, ``Rider``; a column-name phrase with no name word over
  one-word surnames: ``Absent Teacher``) is not suspect either
  (:func:`_foreign_word_count`), unless another cell of the line is a value
  of its column or one more ID, code or number of it.
* footer (:func:`footer_candidate`, K-17): the last 1-3 non-blank lines of a
  multi-column text that hold no quote, a letter or only a rule of symbols,
  and the delimiter only as text punctuation followed by a space
  (``Report generated by Skyward on Monday, October 3, 2025``, ``-----``) are a
  footer block; the CSV reader confirms that they are whole records (and,
  for a note with the delimiter, that no field of the records starts with a
  space) and keeps them as layout text.
"""

from __future__ import annotations

import csv
import io
import itertools
import re
from dataclasses import dataclass, field
from functools import lru_cache
from typing import Any

from ..errors import ReadError
from ..model import ColumnQuoting, Message

SAMPLE_CHARS = 65536
QUOTE_SCAN_CHARS = 1 << 20
#: Sniffing always sees at least this many complete records (header + 2 data records) when the file has them,
#: however long they are (R2-17).
MIN_SAMPLE_RECORDS = 3
CANDIDATE_DELIMITERS = ",\t|;"
#: How common each candidate is inside text (names, numbers, prose): higher = more text-like. The last rule of
#: :func:`sniff_delimiter`: among consistent candidates the least text-like one splits the fields.
TEXT_LIKENESS = {",": 3, ";": 2, "|": 1, "\t": 0}
#: A candidate followed by a space after more than this share of its occurrences is text punctuation.
SPACED_SHARE = 0.5
DELIMITER_NAMES = {",": "comma", ";": "semicolon", "|": "pipe", "\t": "tab"}
LINE_BREAK_RE = re.compile(r"\r\n|\n|\r")
_LINE_BREAK = LINE_BREAK_RE
NUMERIC_RE = re.compile(r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?")

_BOMS = (
    (b"\xef\xbb\xbf", "utf-8"),
    (b"\xff\xfe", "utf-16-le"),
    (b"\xfe\xff", "utf-16-be"),
)


@dataclass
class EncodingInfo:
    encoding: str
    bom: bytes
    confidence: str  # 'bom' | 'strict' | 'low' | 'override'
    messages: list[Message] = field(default_factory=list)


def sniff_encoding(data: bytes, override: str | None = None) -> EncodingInfo:
    """Choose the codec for ``data`` (see module docstring)."""
    bom, bom_codec = b"", None
    for b, codec in _BOMS:
        if data.startswith(b):
            bom, bom_codec = b, codec
            break
    if override:
        o = override.lower().replace("_", "-")
        if bom and (o in ("utf-8", "utf8", "utf-8-sig") and bom_codec == "utf-8" or o.startswith("utf-16") and bom_codec.startswith("utf-16")):
            return EncodingInfo(bom_codec, bom, "override")
        if o == "utf-8-sig":
            o = "utf-8"
        try:
            data.decode(o)
        except LookupError:
            raise ReadError(f"unknown encoding {override!r}", fix="pass a Python codec name to --encoding, e.g. utf-8 or cp1252") from None
        except UnicodeDecodeError as e:
            raise ReadError(f"file is not valid {override}: {e.reason} at byte {e.start}", fix="check --encoding") from None
        return EncodingInfo(o, b"", "override")
    if bom_codec:
        return EncodingInfo(bom_codec, bom, "bom")
    if b"\x00" in data[:SAMPLE_CHARS]:
        raise ReadError(
            "file contains NUL bytes: binary data or UTF-16 text without a byte-order mark",
            fix="if this is UTF-16 text, pass --encoding utf-16-le (or utf-16-be)",
        )
    for codec in ("utf-8", "cp1252"):
        try:
            data.decode(codec)
            return EncodingInfo(codec, b"", "strict")
        except UnicodeDecodeError:
            continue
    msg = Message(
        "warning",
        "encoding_low_confidence",
        "encoding is neither UTF-8 nor cp1252; read as latin-1 (low confidence)",
        fix="pass --encoding if the text looks wrong",
    )
    return EncodingInfo("latin-1", b"", "low", [msg])


def decode(data: bytes, info: EncodingInfo) -> str:
    body = data[len(info.bom):]
    try:
        return body.decode(info.encoding)
    except UnicodeDecodeError as e:  # pragma: no cover - sniff_encoding validated it
        raise ReadError(f"cannot decode as {info.encoding}: {e.reason} at byte {e.start}") from None  # R7-04


@dataclass
class LineEndingInfo:
    line_ending: str
    trailing_newline: bool
    mixed: bool
    counts: dict[str, int]


def sniff_line_ending(text: str) -> LineEndingInfo:
    crlf = text.count("\r\n")
    lf = text.count("\n") - crlf
    cr = text.count("\r") - crlf
    counts = {"\r\n": crlf, "\n": lf, "\r": cr}
    nonzero = [k for k, v in counts.items() if v > 0]
    if not nonzero:
        le = "\n"
    else:
        le = max(("\r\n", "\n", "\r"), key=lambda k: (counts[k], k == "\r\n"))
    return LineEndingInfo(le, text.endswith(("\n", "\r")), len(nonzero) > 1, counts)


def _sample(text: str, limit: int = SAMPLE_CHARS, min_lines: int = MIN_SAMPLE_RECORDS) -> str:
    """The text sniffed: the first ``limit`` chars cut at the last line break, extended to at least
    ``min_lines`` lines (R2-17: a first data record longer than ``limit`` is still in the sample)."""
    if len(text) <= limit:
        return text
    cut = max(text.rfind("\n", 0, limit), text.rfind("\r", 0, limit))
    pos, lines = 0, 0
    while lines < min_lines:
        m = _LINE_BREAK.search(text, pos)
        if m is None:
            return text
        pos, lines = m.end(), lines + 1
    return text[: max(cut + 1, pos)]


def _records(text: str, delimiter: str, limit: int = SAMPLE_CHARS,
             min_records: int = MIN_SAMPLE_RECORDS) -> list[list[str]]:
    """The first COMPLETE records of ``text`` as ``csv.reader`` parses the whole file with ``delimiter``.

    Records are read until ``limit`` characters are consumed, but never fewer than ``min_records`` (when the
    text has them): sniffing sees exactly the records the reader will see, so a record longer than the budget
    (a long comment cell, a very wide header) is evidence like any other instead of being cut off (R2-17).
    """
    # A StringIO copies its input. Start with a bounded physical-line slice;
    # retry when the requested last record reaches its end, since strict=False
    # would otherwise silently accept a quoted field truncated by the slice.
    size = max(limit + 1, 4096)
    while True:
        boundary = _LINE_BREAK.search(text, size)
        end = boundary.end() if boundary else len(text)
        whole = end == len(text)
        f = io.StringIO(text if whole else text[:end], newline="")
        rows: list[list[str]] = []
        try:
            for row in csv.reader(f, delimiter=delimiter, quotechar='"', strict=False):
                rows.append(row)
                if len(rows) >= min_records and f.tell() >= limit:
                    if whole or f.tell() < end:
                        return rows
                    break
        except csv.Error:
            return []
        if whole:
            return rows
        size = max(size * 2, end + 1)


def _consistent(counts: list[int]) -> bool:
    return bool(counts) and counts[0] >= 2 and min(counts) == max(counts)


def _header_line(text: str) -> str:
    m = re.search(r"\r\n|\n|\r", text)
    return text[: m.start()] if m else text


@dataclass
class DelimiterInfo:
    delimiter: str | None
    #: 'override' | 'consistency' (the only consistent candidate) | 'single-column' | how several consistent
    #: candidates were told apart: 'quoting' | 'punctuation' | 'text-likeness' (:func:`sniff_delimiter`)
    method: str
    #: the consistent candidates the chosen one won over -> their field count (empty when only one was consistent)
    alternatives: dict[str, int] = field(default_factory=dict)
    n_fields: int = 0

    @property
    def ambiguous(self) -> bool:
        """Several candidates split every sampled record consistently and only the content-based rules
        (punctuation, text-likeness) told them apart: the guess deserves a warning (the self-check cannot
        contradict it, since it re-reads the output with the same delimiter)."""
        return bool(self.alternatives) and self.method != "quoting"


def delimiter_name(d: str) -> str:
    """A delimiter as messages and fixes name it (``semicolon``, ``tab``; ``--delimiter`` accepts the names)."""
    return DELIMITER_NAMES.get(d, repr(d))


def _stray_quote_fields(records: list[list[str]]) -> int:
    """Fields holding a quote character: a quote encloses a whole field, so a split through a quoted value leaves
    its quotes inside the pieces (the true delimiter's fields hold one only as text: ``5'10"``, ``say ""hi""``)."""
    return sum(1 for r in records for f in r if '"' in f)


def _spaced(records: list[list[str]]) -> bool:
    """The split character is followed by a space at more than :data:`SPACED_SHARE` of the fields it starts (every
    field but a record's first): text punctuation (``Smith, Jane``), not a field separator."""
    after = [f for r in records for f in r[1:] if f]
    return bool(after) and sum(1 for f in after if f[0] == " ") > SPACED_SHARE * len(after)


def sniff_delimiter(text: str, override: str | None = None) -> DelimiterInfo:
    """The delimiter of a delimited text (module docstring, R7-05): the only candidate that splits every sampled
    record into the same number (>= 2) of fields; among several, the one the quoting, then punctuation, then
    text-likeness prefers (:attr:`DelimiterInfo.alternatives` lists the others)."""
    if override:
        return DelimiterInfo(override, "override")
    sample = _sample(text)
    if not sample.strip():
        return DelimiterInfo(",", "single-column" if "," not in sample else "consistency")
    split: dict[str, list[list[str]]] = {}
    for d in CANDIDATE_DELIMITERS:
        records = [r for r in _records(text, d) if r]
        if _consistent([len(r) for r in records]):
            split[d] = records
    if len(split) == 1:
        (d, records), = split.items()
        return DelimiterInfo(d, "consistency", n_fields=len(records[0]))
    if split:
        # every rival's character must sit inside the chosen split's fields: (1) a split that cuts quoted values
        # apart loses, (2) a character that reads as text punctuation loses, (3) the most text-like one loses
        quotes = {d: _stray_quote_fields(r) for d, r in split.items()}
        spaced = {d: _spaced(r) for d, r in split.items()}
        rank = sorted(split, key=lambda d: (quotes[d], spaced[d], TEXT_LIKENESS[d]))
        best, runner = rank[0], rank[1]
        if quotes[best] < quotes[runner]:  # (sorted by quotes first: fewer than every rival)
            method = "quoting"
        elif spaced[best] != spaced[runner]:
            method = "punctuation"
        else:
            method = "text-likeness"
        return DelimiterInfo(best, method, {d: len(split[d][0]) for d in rank[1:]}, len(split[best][0]))
    header = _header_line(text)
    if not any(d in header for d in CANDIDATE_DELIMITERS):
        return DelimiterInfo(None, "single-column")
    found = [repr(d) for d in CANDIDATE_DELIMITERS if d in header]
    raise ReadError(
        f"no delimiter gives a consistent number of fields per row (header contains {', '.join(found)})",
        fix="check the file for ragged rows, or pass --delimiter",
    )


#: K-17: at most this many trailing note lines are a footer note below the data
#: (``Report generated by Skyward on 10/03/2025 2:15 PM``, ``Page 1 of 1``, a ``-----`` rule).
MAX_FOOTER_LINES = 3


@dataclass
class FooterCandidate:
    """A multi-column text whose last 1-3 non-blank lines are note lines (:func:`footer_candidate`).

    ``body``: the text up to and including the line break of the last line before the footer block; ``lines``: the
    footer block in order (``''`` for a blank line before or between the notes, else a note line; it ends with a
    note); ``tail``: the text after the last note (its line break and any trailing blank lines). PRIVATE: the notes
    are real text."""

    body: str
    lines: list[str]
    tail: str

    @property
    def notes(self) -> list[str]:
        return [line for line in self.lines if line]


def note_line(line: str, delimiters: str) -> bool:
    """K-17: ``line`` may be a footer note below the data (:func:`footer_candidate`): it holds no quote character
    (a quote may open a value that spans lines), it holds a letter (``Report generated by Skyward on ...``,
    ``Page 1 of 1``) or is a rule line of symbols (``-----``, ``=====``: no letter, no digit; digits without a
    letter may be a record cut short), and each of ``delimiters`` in it is text punctuation: followed by a space
    (``Monday, October 3, 2025``), never a field separator (``200159,Wilson``)."""
    if '"' in line or not line.strip():
        return False
    if not any(ch.isalpha() for ch in line):
        if any(ch.isdigit() for ch in line) or all(ch.isspace() or ch in delimiters for ch in line):
            return False
    return all(line[i + 1:i + 2] == " " for i, ch in enumerate(line) if ch in delimiters)


def drop_last_lines(text: str, m: int) -> str | None:
    """``text`` up to (and with the line break before) its ``m``-th last non-empty line, or None when that line is
    the first one (K-17: the ragged-tail message)."""
    end = len(text)
    for _ in range(m):
        while end > 0 and text[end - 1] in "\r\n":
            end -= 1  # line breaks and empty lines after the line
        if end == 0:
            return None
        end = max(text.rfind("\n", 0, end), text.rfind("\r", 0, end)) + 1
    return text[:end] if end > 0 else None


def footer_candidate(text: str, delimiter: str | None = None) -> FooterCandidate | None:
    """The footer block of a delimited text, or None (K-17).

    A footer note is one of the last 1-3 non-blank lines of a file whose header line holds a delimiter (``--delimiter``,
    else a candidate delimiter of the header) and a :func:`note_line`: no quote character, a letter or a rule line,
    and a delimiter only as text punctuation followed by a space. Any other line ends the block; so does the header
    (it is never a note), and a fourth note-like line refuses the block (a run of such lines is data that the
    ragged-row check refuses). Blank lines before and between the notes belong to the block. The caller confirms
    that the notes are whole records of the parsed file (not the inside of a quoted multi-line value) and, for a
    note with the delimiter, that no field of the records starts with a space, before treating them as layout
    text.
    """
    header = _header_line(text)
    delims = delimiter or "".join(d for d in CANDIDATE_DELIMITERS if d in header)
    if not delims or not any(d in header for d in delims):
        return None  # a one-column file: every line is a value
    # only the end of the file is read (a footer block is short): its first line may be cut, so it is never a note
    window = text[-SAMPLE_CHARS:] if len(text) > SAMPLE_CHARS else text
    offset = len(text) - len(window)
    breaks = list(_LINE_BREAK.finditer(window))
    starts = [0] + [m.end() for m in breaks]
    ends = [m.start() for m in breaks] + [len(window)]
    lines = [window[a:b] for a, b in zip(starts, ends)]
    i = len(lines) - 1
    while i > 0 and lines[i] == "":
        i -= 1  # trailing blank lines (and the final line break) stay with the file's ending
    last = i
    notes: list[int] = []
    while i > 0:  # line 0: the header (or a line cut by the window), never a note
        line = lines[i]
        if line == "":
            i -= 1
            continue
        if not note_line(line, delims):
            break
        if len(notes) == MAX_FOOTER_LINES:
            return None  # more note-like lines than a footer has
        notes.append(i)
        i -= 1
    if not notes:
        return None
    k = notes[-1] - 1
    while k > 0 and lines[k] == "":
        k -= 1  # the last line before the block (a data record)
    if k < 1 and offset == 0:
        return None  # no data record between the header and the notes
    if lines[k] == "":
        return None  # blank lines all the way up the window
    return FooterCandidate(text[:offset + starts[k + 1]], lines[k + 1:last + 1], text[offset + ends[last]:])


def placeholder_delimiter(text: str) -> str:
    """A delimiter character absent from ``text`` (used for single-column files)."""
    for ch in ("\x1f", "\x1e", "\x1d", "\x1c", "\x07"):
        if ch not in text:
            return ch
    raise ReadError("cannot parse single-column file: control characters everywhere")


