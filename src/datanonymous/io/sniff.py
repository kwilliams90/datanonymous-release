@dataclass
class HeaderProblem:
    """Why the first line does not look like a header (report-safe: positions only)."""

    reasons: list[str]
    prose: bool = False  # single-column file whose first line reads like a sentence
    #: only the value-like signal fired (cells that look like one more value of their column): the line may
    #: still be a header, which ``--header-row 1`` asserts
    record_like: bool = False

    def text(self) -> str:
        return "the first line does not look like a header row: " + "; ".join(self.reasons)


def _cell_shape(h: str) -> str | None:
    if _EMAIL_RE.search(h):
        return "an e-mail address"
    if _SSN_RE.search(h):
        return "an SSN-shaped value"
    if _PHONE_RE.search(h):
        return "a phone-number-shaped value"
    if _URL_RE.fullmatch(h):
        return "a web address"
    if _IPV4_RE.fullmatch(h):
        return "an IP address"
    if _ZIP4_RE.fullmatch(h):
        return "a ZIP+4 code"
    if _STREET_RE.fullmatch(h):
        return "a street address"
    if _DATE_RE.fullmatch(h):
        return "a date-shaped value"
    if _INT_RE.fullmatch(h):
        digits = h.lstrip("+-")
        if len(digits) >= 5 or (len(digits) > 1 and digits.startswith("0")):
            return "a long or zero-padded number"
    if _DEC_RE.fullmatch(h):
        return "a decimal number"
    return None


def header_problems(header: list[str], columns: list) -> HeaderProblem | None:  # noqa: ANN001
    """Return a :class:`HeaderProblem` when ``header`` looks like a data record, else None.

    ``columns`` are the body values per column. Signals: any header cell with a
    data shape (e-mail, SSN, phone, web or IP address, ZIP+4, street address,
    date, a long or zero-padded number, a decimal); two or more non-numeric
    header cells each equal to a value of their own column (unless the whole
    header row is repeated in the body); in a single-column file, a
    sentence-like header (>= 6 words, > 80 characters, or ending in . ! ? with
    >= 3 words); and :func:`record_like` cells (a headerless list of names).
    """
    reasons: list[str] = []
    for i, h in enumerate(header):
        shape = _cell_shape(h.strip())
        if shape:
            reasons.append(f"column {i + 1} holds {shape}")
    prose = False
    if len(header) == 1:
        h = header[0].strip()
        words = len(h.split())
        if words >= PROSE_MIN_WORDS or len(h) > PROSE_MAX_CHARS or (words >= 3 and h.endswith((".", "!", "?"))):
            prose = True
            reasons.append("column 1 reads like a sentence")
    elif len(columns) and len(columns[0]):
        import numpy as np

        from ..profile.codes import codes_of

        def contains(i: int, h: str) -> bool:
            col = columns[i]
            # Reader arrays have an Arrow-backed distinct view in the shared
            # cache. Other callers (including Excel's typed lists) keep their
            # original membership semantics.
            return h in codes_of(col)[1] if isinstance(col, np.ndarray) else h in col

        equal = [i for i, h in enumerate(header)
                 if h.strip() and not _INT_RE.fullmatch(h.strip()) and not _DEC_RE.fullmatch(h.strip())
                 and contains(i, h)]
        if len(equal) >= 2:
            body_rows = zip(*columns)
            repeated = any(row == tuple(header) for row in body_rows)  # a repeated header row is not data
            if not repeated:
                reasons.append(f"{len(equal)} column(s) ({', '.join(str(i + 1) for i in equal[:5])}) repeat a value "
                               "of their own column")
    if not reasons:
        suspects = record_like_cells(header, columns)
        if suspects:
            reasons.append(f"column(s) {', '.join(str(i + 1) for i in suspects[:5])} hold words that are no "
                           "recognisable column name and look like one more value of their column (names, codes or "
                           "text), and no other cell is a recognisable column name over different values")
            return HeaderProblem(reasons, prose, record_like=True)
    return HeaderProblem(reasons, prose) if reasons else None


def _str_values(col: Any) -> list[str]:  # noqa: ANN401 - a sequence of cell values (str, numbers, None ...)
    """Non-blank text values of a column sample, stripped; a typed cell (Excel number, date) becomes ``0``."""
    from ..hints import DEFAULT_NA_TOKENS

    out: list[str] = []
    for v in itertools.islice(col, RECORD_LIKE_SAMPLE):
        if v is None:
            continue
        if not isinstance(v, str):
            out.append("0")  # a typed cell (number, date, boolean): never a name, code or text of a record
            continue
        s = v.strip()
        if s and s not in DEFAULT_NA_TOKENS:
            out.append(s)
    return out


def _name_shaped(v: str) -> bool:
    return len(v.split()) <= NAME_MAX_WORDS and _NAME_SHAPED_RE.fullmatch(v) is not None


def _signature(v: str) -> str:
    """Character-class shape, case-blind: letters -> a, digits -> 9, runs collapsed (``S1001`` -> ``a9``)."""
    out: list[str] = []
    for ch in v:
        c = "a" if ch.isalpha() else "9" if ch.isdigit() else " " if ch.isspace() else ch
        if not out or out[-1] != c:
            out.append(c)
    return "".join(out)


def _content_tokens(h: str) -> list[str]:
    from .. import hints

    return [t for t in hints.tokens(h) if t.isalpha() and len(t) >= 2 and t not in _STOP_WORDS]


@lru_cache(maxsize=1)
def _header_words() -> frozenset[str]:
    from .. import hints

    return (GENERIC_HEADER_WORDS | frozenset(_HEADER_WORD_KINDS) | frozenset(hints.NON_PERSON_NOUNS)
            | frozenset(hints.PERSON_ROLE_WORDS) | hints.localized_header_words()  # R3-04: Nombre, Apellido ...
            | frozenset(hints.ORG_CODE_WORDS) | frozenset(hints.PERSON_ID_WORDS) | frozenset(hints.ID_WORDS))


def _header_word(t: str, words: frozenset[str]) -> bool:
    return t in words or (t.endswith("s") and t[:-1] in words) or (t.endswith("es") and t[:-2] in words)


def _column_name_words(h: str) -> bool:
    """Every word of ``h`` is a column-name word (``Gender``, ``Home Language``, ``Race/Ethnicity``,
    ``Student Name``); a word that is also a common surname (``Price``) does not count."""
    toks = _content_tokens(h)
    words = _header_words() - _SURNAME_WORDS
    return bool(toks) and all(_header_word(t, words) for t in toks)


def _known_header(h: str) -> bool:
    """A column-name word anywhere in ``h`` (whole words only: the prefix rules of the header hints would take
    surnames such as ``Townsend`` or ``Keyes`` for column names)."""
    words = _header_words()
    return any(_header_word(t, words) for t in _content_tokens(h))


def _name_cell(h: str) -> bool:
    """A name or label cell: name-shaped with at least two letters (one letter, an initial or a toy column
    name ``a``, names nobody)."""
    return _name_shaped(h) and sum(1 for ch in h if ch.isalpha()) >= 2


def _code_cell(h: str) -> bool:
    """An ID or code cell (``S1001``): one token of >= 4 characters with >= 2 digits (``c0``, ``Q1`` identify
    nobody)."""
    return " " not in h and len(h) >= MIN_CODE_CHARS and sum(1 for ch in h if ch.isdigit()) >= 2


def _may_be_value(h: str) -> bool:
    """Value-free part of :func:`_value_like`: a name, code or text cell that is no column-name phrase."""
    if not any(ch.isalpha() for ch in h) or _column_name_words(h):
        return False
    return _name_cell(h) or _code_cell(h) or (not _name_shaped(h) and len(h.split()) >= PROSE_CELL_WORDS)


def _may_vouch(h: str) -> bool:
    """Value-free part of :func:`_vouches`: a column-name word or an identifier shape."""
    return any(ch.isalpha() for ch in h) and (_known_header(h) or _IDENTIFIER_RE.fullmatch(h) is not None)


def _value_like(h: str, vals: list[str]) -> bool:
    """``h`` could be one more value of its column: a name or label over a column of names/labels, a code over
    codes of the same shape, or text over text, and ``h`` is no column-name phrase."""
    if not vals or not _may_be_value(h):
        return False
    need = RECORD_LIKE_SHARE * len(vals)
    if _name_shaped(h):
        if not _name_cell(h):
            return False
        if h.casefold() not in _FLAG_WORDS and sum(1 for v in vals if v.casefold() in _FLAG_WORDS) >= need:
            return False  # a word over a column of flags (Active over TRUE/FALSE) heads it
        if len(h) > SHORT_CODE_CHARS and sum(1 for v in vals if len(v) <= SHORT_CODE_CHARS) >= need:
            return False  # a word over one- and two-letter codes (grp over a/b/c, Sex over F/M) heads them
        return sum(1 for v in vals if _name_shaped(v)) >= need
    if _code_cell(h):  # an ID or code over IDs or codes of the same shape (S1001 over S1002 ...)
        sig = _signature(h)
        return sum(1 for v in vals if _signature(v) == sig) >= need
    if len(h.split()) >= PROSE_CELL_WORDS:  # text over text (a comment of a headerless file)
        return sum(1 for v in vals if len(v.split()) >= PROSE_CELL_WORDS) >= 0.5 * len(vals)
    return False


def _vouches(h: str, vals: list[str]) -> bool:
    """``h`` is a recognisable column name (hint, column-name word or identifier shape) over a column of
    numbers, dates, codes or e-mails (>= 90% of the values hold a digit or ``@``: a word there is no value of a
    record) that does not look like a value of its own column (its shape is held by < 10% of the values, and
    it is none of them). A word over a column of words or text never vouches: such a column can hold it."""
    if not h or not vals or not _may_vouch(h):
        return False
    if sum(1 for v in vals if "@" in v or any(ch.isdigit() for ch in v)) < RECORD_LIKE_SHARE * len(vals):
        return False
    key, sig = h.casefold(), _signature(h)
    if any(v.casefold() == key for v in vals):
        return False
    return sum(1 for v in vals if _signature(v) == sig) < (1 - RECORD_LIKE_SHARE) * len(vals)


def _plain_words(h: str) -> bool:
    """K-15: every word of ``h`` is a known word that names nobody: a column-name word (:func:`_header_words`) or
    an everyday word (``detect.names.common_words``: ``Kid``, ``Flower``), and none is on the given-name or
    surname lists (``detect.names.known_names``: ``Buddy``, ``House``, ``Price`` are). A rare name is on neither
    list, so it is never a plain word."""
    from ..detect import names

    if any(ch.isdigit() for ch in h):
        return False
    toks = _content_tokens(h)
    if not toks:
        return False
    first, last = names.known_names()
    common = names.common_words()
    words = _header_words()
    for t in toks:
        f = names.fold_word(t)
        if not f or f in first or f in last:
            return False
        if not (_header_word(t, words) or _header_word(f, common)):
            return False
    return True


def _heads_column(h: str, vals: list[str]) -> bool:
    """K-15: ``h`` is no value of its column of names: a :func:`_plain_words` cell that occurs nowhere in a column
    of name-shaped values among which no plain word occurs (so one in the first line would be no value of theirs).
    ``Kid`` over ``Isabella``/``Mateo``, and over names that are on no list (``Oluwaseun``/``Hodan``: K15-A2);
    never a rare name (``Zelmira``: on no word list) or a name (``Buddy``: on the given-name list). Such a cell is
    not suspect; it vouches for the other cells of the line only over known names (:func:`_heads_names`)."""
    from collections import Counter

    if not vals or not _plain_words(h) or sum(1 for v in vals if _name_shaped(v)) < RECORD_LIKE_SHARE * len(vals):
        return False
    key = h.casefold()
    counts = Counter(vals)
    if any(v.casefold() == key for v in counts):
        return False
    return not any(_plain_words(v) for v in counts)


def _heads_names(h: str, vals: list[str]) -> bool:
    """K-15: ``h`` heads a column of known people's names: a :func:`_heads_column` cell over known given names or
    surnames (``detect.names.name_value_verdict``). ``Kid`` over ``Isabella``/``Mateo``, ``Mentor`` over
    ``Garcia``/``Nguyen``; never a word over a column of words or of names on no list (``Figure`` over shapes)."""
    from collections import Counter

    from ..detect import names

    return _heads_column(h, vals) and names.name_value_verdict(Counter(vals)) is not None


def _foreign_word_count(h: str, vals: list[str]) -> bool:
    """K15-ATK-2: ``h`` has a number of words that no value of its column has, over >= 10 values, and ``h`` is
    nobody's full name: one word of letters (``Recipient`` or ``Nominee`` over ``Isabella Garcia``, ``Rider`` over
    ``Garcia Mateo``, ``Lane`` over ``Lane A``), or words on no given-name or surname list among which is a
    column-name word (``Absent Teacher`` over surnames). Its word pattern occurs nowhere in the column, so it is
    no value of it whatever its words are: a headerless first record would have to hold the only value of its
    word count in the column, and then only a single word or a column-name phrase, never a full name (G3).
    Over one-word names a one-word cell is never foreign (``Zelmira`` over given names stays a suspect)."""
    from ..detect import names

    n = len(h.split())
    if len(vals) < WORD_COUNT_MIN_VALUES or any(len(v.split()) == n for v in vals):
        return False
    if n == 1:
        return h.isalpha()
    toks = _content_tokens(h)
    first, last = names.known_names()
    if not toks or any(names.fold_word(t) in first or names.fold_word(t) in last for t in toks):
        return False
    words = _header_words() - _SURNAME_WORDS
    return any(_header_word(t, words) for t in toks)


def _record_cell(h: str, vals: list[str]) -> bool:
    """``h`` is a value of its column (``Citizenship`` over awards that hold it), or it holds a digit and has the
    character shape of >= 90% of its column's values: one more ID, code or number of the column (``1001`` over
    ``1002``, ``S1000`` over ``S1001``)."""
    if not vals:
        return False
    key = h.casefold()
    if any(v.casefold() == key for v in vals):
        return True
    if not any(ch.isdigit() for ch in h):
        return False
    sig = _signature(h)
    return sum(1 for v in vals if _signature(v) == sig) >= RECORD_LIKE_SHARE * len(vals)


def record_like_cells(header: list[str], columns: list) -> list[int]:  # noqa: ANN001 - sequences of cell values
    """Positions of header cells that may be one more data record's values (R1-06, R2-05), or [].

    Judged per cell, never per row, and never by letter case: a cell is suspect when it is no column-name
    phrase and looks like one more value of its column (:func:`_value_like`: ``Zelmira`` or ``ZELMIRA`` over
    names, ``Quenby, Z`` over "Last, First" names, ``S1001`` over IDs), unless it heads a column of names
    (:func:`_heads_column`: ``Kid`` over given names, a known word that names nobody and that the column does not
    hold, K-15) or its number of words occurs nowhere in its column (:func:`_foreign_word_count`: ``Recipient``
    over full names, K15-ATK-2; not when another cell of the line is a value of its column or one more ID, code
    or number of it, :func:`_record_cell`). The line is a header anyway when another cell vouches for it
    (:func:`_vouches`: ``Score`` over numbers, ``student_id`` over IDs; or :func:`_heads_names`: ``Mentor`` over
    surnames, K-15, unless a suspect cell is an ID or code over IDs or codes of its shape); otherwise it is
    refused (its text would be copied verbatim as column names) unless the user asserts it is the header
    (``--header-row 1``).
    """
    from ..hints import DEFAULT_NA_TOKENS

    if not header or len(columns) != len(header):
        return []
    cells = [h.strip() if isinstance(h, str) else "" for h in header]
    cache: dict[int, list[str]] = {}
    heads: dict[int, bool] = {}

    def values(i: int) -> list[str]:  # a column's sample, read only for the cells that need it (wide files)
        if i not in cache:
            cache[i] = _str_values(columns[i])
        return cache[i]

    def heads_column(i: int) -> bool:
        if i not in heads:
            heads[i] = _heads_column(cells[i], values(i))
        return heads[i]

    def heads_names(i: int) -> bool:
        from collections import Counter

        from ..detect import names

        return heads_column(i) and names.name_value_verdict(Counter(values(i))) is not None

    suspects = [i for i, h in enumerate(cells)
                if h and h not in DEFAULT_NA_TOKENS and _may_be_value(h) and _value_like(h, values(i))
                and not heads_column(i)]
    # K15-ATK-2: a cell whose word count its column never has is no value of it (Recipient over full names),
    # unless another cell of the line is a value of its column or one more ID, code or number of it: then the line
    # is a record (whose ID would be copied as a column name, G1), and the word may be its own one-word value.
    foreign = [i for i in suspects if _foreign_word_count(cells[i], values(i))]
    if foreign and not any(_record_cell(h, values(i)) for i, h in enumerate(cells)
                           if i not in foreign and h and h not in DEFAULT_NA_TOKENS):
        suspects = [i for i in suspects if i not in foreign]
    if not suspects:
        return []
    if any(_vouches(h, values(i)) for i, h in enumerate(cells)
           if i not in suspects and h and h not in DEFAULT_NA_TOKENS and _may_vouch(h)):
        return []
    # K-15: a known word over people's names vouches for an all-text line only. Such a word can be a record's own
    # placeholder value (``TBD``, ``Staff`` in a teacher column), so it never rescues a cell that looks like one
    # more ID or code of its column (``S1000`` over ``S1001`` ...): that line is a record (its ID and names would
    # be copied verbatim as column names).
    if not any(_code_cell(cells[i]) for i in suspects) and any(
            heads_names(i) for i, h in enumerate(cells)
            if i not in suspects and h and h not in DEFAULT_NA_TOKENS and _plain_words(h)):
        return []
    return suspects


def record_like(header: list[str], columns: list) -> bool:  # noqa: ANN001 - sequences of cell values
    """True when the header row may be one more data record (:func:`record_like_cells`)."""
    return bool(record_like_cells(header, columns))
