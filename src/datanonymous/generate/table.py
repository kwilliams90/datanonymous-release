"""Synthetic table assembly (FOUNDATION; calls every generation hook).

Order (design 5.1, D3, D4, D6, D8):

0. Same-shape pseudonyms for the real text units the copy gate's D35 allowlist
   did not keep (``generate.pseudonyms``): one pseudonym per real unit, used by
   every path below that writes the column's levels, items or tokens; and
   (R9-01) for the real values that are real person IDs of the run, discrete
   numbers included; a continuous number column redraws every generated value
   equal to one of its real numbers that is a real ID
   (``numeric.avoid_real_ids``), so no path writes a real ID verbatim.
1. ID columns: the run-level registry's synthetic ID written at each real row
   position (1:1 per run, exact rows per ID, same mapping in every file).
2. Within-ID-constant columns (D4): one value per synthetic entity (generated
   from the per-entity distribution, with every source level and the exact
   min/max floored in by ``profile.table.floor_entity_levels`` /
   ``floor_entity_extremes``), repeated on all its rows. Their blank/non-blank
   slots follow one joint pattern per entity (D6,
   ``profile.structure.sample_entity_mask``). Patterns, levels and NA tokens
   are dealt to the ID blocks so their row counts stay as in the source too
   (``profile.structure.balance_entity_rows``; R2-10), and numbers and dates
   by value bins of at least ``--min-cell`` IDs, so their written rows keep
   the source's distribution (``profile.structure.balance_entity_numbers``;
   R3-07).
3. Whole-row missingness pattern for the row-level columns (D6), dealt to the
   rows of each entity pattern in the real proportions.
4. Every other column generated independently (D3) into its non-missing slots;
   missing slots get the real NA tokens verbatim by exact quota (floor >= 1).
   Then ``pii.avoid_real_full_names``: a synthetic full name, or a synthetic
   last name that pairs with a synthetic first/middle name of the table, that
   spells a real person's full name anywhere in the run is redrawn (R1-04).
   Throughout, a value holding a real phone number or SSN of the run (a
   phone/SSN-shaped token, ``privacy.digits``) is redrawn like a real value,
   and so is one equal to a real text of any column of the run that the run
   never writes (``privacy.texts``, R7-01/R7-02).
5. ``profile.structure.apply_structure`` (AREA D structural switches: declared
   rules, functional dependencies, derived templates, composite keys; see
   ``generate.structure``). Row-level layout (composite-key repair, duplicate
   rows, sort order) runs after privacy swap-redraw, in the pipeline's call to
   ``profile.structure.finalize_rows``.
6. R8-05: every ``--na-value`` token the D35 allowlist did not keep
   (``detect.text.decide_na_tokens``) is replaced by its pseudonym in whatever
   column wrote it (``generate.pseudonyms.apply_na_map``); the pseudonym is one
   of the column's NA tokens, so it is still read as missing.

Generators never see a real row: they get the column profile and its private
model (counts, sorted numbers, real-value sets). ``generate/`` never imports
``io/``.
"""

