# =========================================================================== K-17 CSV footer notes
NOTE = "Report generated by Skyward on 10/03/2025 2:15 PM"


def _grades_text(n: int = 60, le: str = "\n", footer: str = NOTE, gap: int = 0, ending: str = "\n") -> str:
    rng = random.Random(17)
    lines = ["student_id,grade,score"] + [f"{100000 + i},{rng.choice(['09', '10', '11', '12'])},{rng.randint(55, 99)}"
                                          for i in range(n)]
    text = le.join(lines) + le + le * gap + le.join(footer.split("\n"))
    return text + ending.replace("\n", le)


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    return path


@pytest.mark.parametrize("le,gap,footer,ending", [
    ("\n", 0, NOTE, "\n"),
    ("\r\n", 1, NOTE, "\n"),  # the ending is given with LF and written with the file's line ending
    ("\n", 0, NOTE, ""),  # no final line break
    ("\n", 2, NOTE + "\n\nPage 1 of 1\nConfidential", "\n\n"),  # three notes, blank lines, a trailing blank line
])
def test_k17_footer_notes_are_layout_text(tmp_path: Path, le: str, gap: int, footer: str, ending: str) -> None:
    src = _write(tmp_path / "in" / "grades.csv", _grades_text(le=le, gap=gap, footer=footer, ending=ending))
    res, out, rep = _run(src.parent, tmp_path)
    assert res.exit_code == 0, res.output
    entry = _entry(rep, "grades.csv")
