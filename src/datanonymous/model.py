"""Core data contracts shared by every stage (FOUNDATION; shared file).

Nothing in this module does work: it defines the enums and dataclasses that the
readers, detectors, profilers, generators, writers and reports exchange. Area
agents read these contracts but do not edit this file; format- or type-specific
details travel in the free-form ``params`` / ``extra`` / ``native`` dicts.

Real-data hygiene
-----------------
Two kinds of real-derived information exist:

* **public aggregates** (``ColumnProfile.stats``, ``TableProfile.entity`` counts,
  ...). They are written to the report directory and must follow design D21:
  no real ID/name/email/phone/address/free-text value, real labels only for
  label-safe types (see :data:`LABEL_SAFE_TYPES`).
* **private models** (:class:`ColumnModel`, :class:`TablePrivate`). They hold real
  values in memory (level counts, sorted numbers, real ID sets, row keys) for
  generation and privacy checks only. They are never serialised; every
  ``to_public()`` helper drops them.
"""

