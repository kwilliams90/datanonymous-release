# =========================================================================== K-20 native non-finite numbers
def _x(n: int = 60) -> list[float]:
    rng = random.Random(20)
    x = [round(rng.uniform(0, 100), 2) for _ in range(n)]
    x[3], x[9], x[17], x[25] = math.inf, -math.inf, math.inf, math.nan
    return x


def _kinds(values: list) -> Counter:
    return Counter("null" if v is None else "nan" if v != v else "inf" if v == math.inf else "-inf"
                   if v == -math.inf else "num" for v in values)


@pytest.mark.parametrize("kind", ["parquet", "feather32"])
def test_k20_arrow_non_finite_doubles_are_kept(tmp_path: Path, kind: str) -> None:
    x = _x()
    y = [i % 5 for i in range(len(x))]
    (tmp_path / "in").mkdir()
    if kind == "parquet":
        name = "t.parquet"
        pq.write_table(pa.table({"x": pa.array(x, pa.float64()), "y": y}), tmp_path / "in" / name)
    else:
        name = "t.feather"
        feather.write_feather(pa.table({"x": pa.array(x, pa.float32()), "y": y}), tmp_path / "in" / name)
    res, out, rep = _run(tmp_path / "in", tmp_path)
    assert res.exit_code == 0, res.output
    back = (pq.read_table if kind == "parquet" else feather.read_table)(out / name)
    assert back.schema.field("x").type == (pa.float64() if kind == "parquet" else pa.float32())
    assert _kinds(back["x"].to_pylist()) == _kinds(x)  # +inf, -inf and NaN at their exact counts
    col = _columns(rep, name)["x"]
    assert col["type"] == "FLOAT"
    finite = [v for v in x if math.isfinite(v)]
    real = col["real"]
    assert real["min"] == pytest.approx(min(finite)) and real["max"] == pytest.approx(max(finite))
    assert real["missing_tokens"] == {"inf": 2, "-inf": 1, "NaN": 1}  # kept like NaN, out of the statistics


