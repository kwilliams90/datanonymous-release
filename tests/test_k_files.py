@pytest.mark.parametrize("placeholder", ["TBD", "Staff", "Pending", "Vacant", "Unassigned"])
def test_k15_a_word_never_rescues_a_first_line_id(tmp_path: Path, placeholder: str) -> None:
    """Hardening (G1): a known word over people's names can be a record's own placeholder value (the first
    student's teacher is TBD). It never vouches for a first line whose ID looks like one more ID of its column: the
    headerless roster FAILs instead of copying the student's ID and name as column names."""
    first = ["S1000", "Okonkwo", "Chidi", placeholder]
    rows = _roster()
    prob = sniff.header_problems(first, _cols(rows))
    assert prob is not None and prob.record_like
    # a real header over the same records is still a header
    assert sniff.header_problems(["Student ID", "Last", "First", "Teacher"], _cols(rows)) is None
    src = tmp_path / "in" / "roster.csv"
    src.parent.mkdir(parents=True)
    src.write_text("\n".join(",".join(r) for r in [first, *rows]) + "\n", encoding="utf-8")
    res, out, rep = _run(src.parent, tmp_path)
    assert res.exit_code == 3, res.output
    assert not (out / "roster.csv").exists()
    texts = _texts(out, rep) + res.output
    assert not any(v in texts for v in ("S1000", "Okonkwo", "Chidi"))


