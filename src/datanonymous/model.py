@dataclass
class FileResult:
    rel_path: str
    out_rel_path: str
    format: str
    status: Status = Status.PASS
    written: bool = False
    reasons: list[str] = field(default_factory=list)
    fixes: list[str] = field(default_factory=list)
    messages: list[Message] = field(default_factory=list)
    layout: FileLayout | None = None
    out_layout: FileLayout | None = None
    tables: list[TableProfile] = field(default_factory=list)
    synthetic_stats: list[dict[str, Any]] = field(default_factory=list)  # per table: column index -> stats
    fidelity: list[dict[str, Any]] = field(default_factory=list)  # per table: column index -> verdict
    privacy: list[dict[str, Any]] = field(default_factory=list)  # per table
    selfcheck: list[str] = field(default_factory=list)
    source_dtypes: list[list[str] | None] = field(default_factory=list)
    out_dtypes: list[list[str] | None] = field(default_factory=list)
    #: D34 (``privacy.headers``): a name this file would write holds personal data; its details (column table,
    #: sheet names, layout, column messages) are left out of the report and the console
    withheld: bool = False
    #: PRIVATE (D34): the real out-dir relative path when ``rel_path`` / ``out_rel_path`` show a redacted
    #: folder or file name; used only to find an earlier copy in the out dir, never printed
    out_rel_real: str | None = None
    #: PRIVATE: verification parse of the bytes written to disk, never reported.
    _reread: ReadResult | None = field(default=None, repr=False, compare=False)
    _reread_key: tuple[int, int, int] | None = field(default=None, repr=False, compare=False)
    _reread_cells: int = field(default=0, repr=False, compare=False)

    def clear_reread(self) -> None:
        self._reread = None
        self._reread_key = None
        self._reread_cells = 0

    @property
    def out_rel_on_disk(self) -> str:
        """Where the output is (or an earlier copy would be) in the out dir (PRIVATE when redacted, D34)."""
        return self.out_rel_real or self.out_rel_path

    @property
    def failed(self) -> bool:
        return self.status is Status.FAIL

    def fail(self, reason: str, fix: str | None = None, code: str | None = None,
             column: str | None = None) -> None:
        """FAIL the file. ``code`` names the message-catalogue entry that explains it in plain language."""
        self.clear_reread()
        self.status = Status.FAIL
        self.written = False
        self.reasons.append(reason)
        if fix:
            self.fixes.append(fix)
        self.messages.append(Message("error", code or "fail", reason, column=column, fix=fix))

    def all_messages(self) -> list[Message]:
        out = list(self.messages)
        for t in self.tables:
            out.extend(t.messages)
            for c in t.columns:
                out.extend(c.messages)
        return out

    def finalize_status(self) -> None:
        if self.status is Status.FAIL:
            return
        if any(m.level in ("warning", "error") for m in self.all_messages()):
            self.status = Status.WARN
        else:
            self.status = Status.PASS


@dataclass
class RunResult:
    mode: str  # 'run' | 'inspect'
    input: Path
    out_dir: Path | None
    report_dir: Path | None
    seed: int
    seed_was_random: bool
    files: list[FileResult] = field(default_factory=list)
    skipped: list[SkippedFile] = field(default_factory=list)
    messages: list[Message] = field(default_factory=list)
    docs: dict[str, str] = field(default_factory=dict)  # doc kind -> out-dir relative path
    debug: list[str] = field(default_factory=list)  # tracebacks of internal errors (stderr with -v only)
    data_mode: str = "fidelity"
    package: dict[str, Any] | None = None  # local sharing-package evidence, never part of the released data
    #: PRIVATE: files planned for writing that FAILed during generation or were withheld after it; sharing runs
    #: again without them, because every run-wide plan (row-number IDs, real-text excuses) assumed they were written
    late_failures: list[FileResult] = field(default_factory=list, repr=False, compare=False)
    #: PRIVATE: sharing (ADR-0001): file -> table number -> column index -> (plain reason, alternative) of the non-key
    #: columns whose blocking findings after generation were the file's only ones; sharing runs again with them nulled
    null_requests: dict[str, dict[int, dict[int, tuple[str, str | None]]]] = field(
        default_factory=dict, repr=False, compare=False)

    @property
    def any_failed(self) -> bool:
        return any(f.failed for f in self.files)

    def totals(self) -> dict[str, int]:
        return {
            "files": len(self.files),
            "PASS": sum(f.status is Status.PASS for f in self.files),
            "WARN": sum(f.status is Status.WARN for f in self.files),
            "FAIL": sum(f.status is Status.FAIL for f in self.files),
            "skipped": len(self.skipped),
        }
