# --------------------------------------------------------------------------- K15-ATK-2 word patterns
AWARDS = ["Honor Roll", "Principal's List", "Perfect Attendance", "Citizenship", "Most Improved"]
STOPS = ["Elm & 5th", "Oak Park", "Maple Ave", "Lincoln Blvd", "Cedar Ct"]


def _people(n: int = 60, seed: int = 152) -> list[tuple[str, str]]:
    rng = random.Random(seed)
    return [(rng.choice(GIVEN), rng.choice(SURNAMES)) for _ in range(n)]


def _full(n: int = 60) -> list[str]:
    return [f"{g} {s}" for g, s in _people(n)]


def _cycle(words: list[str], n: int = 60) -> list[str]:
    return [words[i % len(words)] for i in range(n)]


@pytest.mark.parametrize("header,cols", [
    (["Recipient", "Award"], [_full(), _cycle(AWARDS)]),
    (["Nominee", "Award"], [_full(), _cycle(AWARDS)]),
    (["Rider", "Stop"], [[f"{s} {g}" for g, s in _people()], _cycle(STOPS)]),
    (["Rider", "Stop"], [[f"{s}, {g}" for g, s in _people()], _cycle(STOPS)]),
    (["Swimmer", "Lane"], [_full(), _cycle(["Lane A", "Lane B"])]),  # Lane is a name, but no full name
    (["Reader", "Book"], [_full(), _cycle(["Holes", "Wonder", "Hatchet", "Matilda"])]),
    (["Sub", "Absent Teacher"], [_full(), [s for _, s in _people()]]),  # a column-name phrase over surnames
])
def test_k15_atk2_header_words_over_names_of_another_word_count(header: list[str], cols: list[list[str]]) -> None:
    """K15-ATK-2 (attack): ``Recipient,Award`` over ``Isabella Garcia,Honor Roll`` FAILed as headerless: Recipient
    is on no word list. Its number of words is held by no value of its column (one word over full names), so it is
    no value of that column; a single word is no full name (G3)."""
    assert sniff.header_problems(header, cols) is None


@pytest.mark.parametrize("header,cols", [
    # another cell is one more ID, code or number of its column: a record, whose ID would be a column name (G1)
    (["Okonkwo", "7302"], [_full(), [str(7303 + i) for i in range(60)]]),
    (["Okonkwo", "S7302"], [_full(), [f"S{7303 + i}" for i in range(60)]]),
    (["Okonkwo", "11"], [_full(), _cycle(["9", "10", "11", "12"])]),
    # another cell is a value of its column (a column-name word too: Citizenship), or looks like one
    (["Okonkwo", "Citizenship"], [_full(), _cycle(AWARDS)]),
    (["Okonkwo", "Honor Roll"], [_full(), _cycle(AWARDS)]),
    # the column holds a one-word value too, or fewer than 10 values: its word pattern is no evidence
    (["Okonkwo", "Award"], [_full()[:-1] + ["Cher"], _cycle(AWARDS)]),
    (["Okonkwo", "Award"], [_full(9), _cycle(AWARDS, 9)]),
    # one word over one-word names; a phrase with a name word or without a column-name word over one-word names
    (["Zelmira", "Award"], [[g for g, _ in _people()], _cycle(AWARDS)]),
    (["Garcia Teacher", "Award"], [[s for _, s in _people()], _cycle(AWARDS)]),
    (["Zelmira Quenby", "Award"], [[g for g, _ in _people()], _cycle(AWARDS)]),
    # full names over full names, and a full name over one-word names
    (["Zelmira Quenby", "Award"], [_full(), _cycle(AWARDS)]),
    (["Zelmira Quenby"], [[s for _, s in _people()]]),
])
def test_k15_atk2_headerless_records_are_still_refused(header: list[str], cols: list[list[str]]) -> None:
    prob = sniff.header_problems(header, cols)
    assert prob is not None and prob.record_like
    assert not any(h in prob.text() for h in header)  # positions only


