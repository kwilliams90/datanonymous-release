"""CSV/TSV/TXT reader and byte-faithful writer (FOUNDATION).

Reading (design 6): raw bytes -> encoding sniff (BOM, strict utf-8, strict
cp1252, latin-1) -> line ending, delimiter and quoting sniff -> ``csv.reader``
over the exactly decoded text (``newline=''``). Every field stays a raw string
(no NA conversion, no type inference, whitespace kept), so duplicate/blank
header names, ``'Central '`` and the level ``'NA'`` survive. Rows with a field
count different from the header fail the file (fix: ``--delimiter``), except a
footer (K-17): the last 1-3 non-blank lines of a multi-column file that are
notes (``Report generated by Skyward on Monday, October 3, 2025``, a ``-----``
rule: a letter or only symbols, no quote, the delimiter only as text
punctuation followed by a space while no field of the records starts with a
space, each a whole record; ``sniff.footer_candidate``,
:func:`_split_footer`) are layout text below the data, not records; ragged
last lines that are no such notes fail with a message that names them
(:func:`ragged_tail_error`, never their text). They are kept PRIVATE in the table
layout (``_footer_rows``, as Excel footer rows: the run's real-text registry,
the leak scan and, with ``--keep-titles``, the D34 screen read them through
``privacy.texts.layout_texts``) and written back in place, blank lines
included, as same-shape placeholders (``io.excel_write.Placeholders``;
``--keep-titles``: verbatim), so N data rows in = N out. A delimiter
chosen among several candidates that each split every sampled line consistently
(``sniff.sniff_delimiter``, decided by punctuation or text-likeness rather than
the quoting) is a ``delimiter_ambiguous`` warning with the ``--delimiter`` fix,
and the report flags the layout self-check (R7-05). Blank lines
at the end of the file are recorded and rewritten; blank lines between records
are dropped with a warning (in a single-column file a blank line is a blank value).

The first line must look like a header (``sniff.header_problems``): a file whose
first line looks like a data record (no header row) FAILs with the fix "add a
header row", because the header is written verbatim to the output, the docs
and the report. A first line with a cell that names no recognisable column and
looks like one more value of its column (a name over names in any letter case,
an ID over IDs: a headerless list of names), with no other cell that is a
recognisable column name over numbers, dates, codes or e-mails, fails too
(``sniff.record_like_cells``), with the extra fix ``--header-row 1``, which
asserts that the first line is the header row and skips these checks (as
``--header-row`` does for Excel). A
``.txt`` file whose single "header" reads like a sentence is prose, not a
table: :class:`~datanonymous.errors.NotTabular` (listed as skipped, never
copied, D18).

Writing: our own writer (``csv.writer`` has one quoting mode per writer and
``to_csv`` converts LF to CRLF on Windows). It reproduces delimiter, quote
character, per-column quoting (minimal / always / nonnumeric, quoted empties),
the raw header and its quoting, line ending, encoding + BOM, trailing newline
and trailing blank lines, bare quote characters inside unquoted fields
(``5'10"``), and in single-column files the quoting of values that contain a
candidate delimiter (pandas quotes ``"Smith, J"``). Reading then writing
without generation reproduces a consistently formatted file byte for byte. A
single-column file without a final line break cannot end with a blank value (it
would read back as a line break): the writer moves such a blank to the last
non-blank row of the column (values and counts unchanged).

A table written with fewer columns than its source (``--exclude``) keeps the
source dialect except what the written table cannot carry
(:func:`written_dialect`, shared by the writer and the self-check, R6-06): a
one-column output shows no delimiter (values holding the source's delimiter are
still quoted for it, and the self-check re-reads the output with the source's
delimiter), writes no trailing blank lines (each would read back as a blank
value), ends with a line break when every value is blank, and quotes a blank
header.
"""

