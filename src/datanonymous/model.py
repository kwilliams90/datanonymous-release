@dataclass
class ColumnModel:
    """PRIVATE in-memory generation model (never serialised; design 5.2.1).

    * ``nonmissing_counts`` / ``missing_counts``: raw value -> count, split by the
      column's missing policy. Insertion order = first appearance (deterministic).
    * ``sorted_numeric``: sorted real numeric values (continuous generators).
    * ``lengths``: sorted raw lengths of non-missing values (text generators).
    * ``real_values``: stripped real values, used to guarantee never-copy types
      never emit a real value.
    """

    nonmissing_counts: dict[Any, int] = field(default_factory=dict)
    missing_counts: dict[Any, int] = field(default_factory=dict)
    sorted_numeric: np.ndarray | None = None
    lengths: np.ndarray | None = None
    real_values: frozenset[str] | None = None
    extra: dict[str, Any] = field(default_factory=dict)

    @property
    def n_nonmissing(self) -> int:
        return int(sum(self.nonmissing_counts.values()))

    @property
    def n_missing(self) -> int:
        return int(sum(self.missing_counts.values()))


