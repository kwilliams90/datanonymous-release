_PII_TYPES = frozenset({ColumnType.EMAIL, ColumnType.PERSON_NAME, ColumnType.PHONE, ColumnType.SSN, ColumnType.ZIP,
                        ColumnType.STATE, ColumnType.CITY, ColumnType.STREET_ADDRESS, ColumnType.IP, ColumnType.URL})
_B_TYPES = frozenset({ColumnType.NUMERIC_FORMATTED, ColumnType.NUMERIC_WITH_TOKENS, ColumnType.DECIMAL})
_CONTINUOUS = frozenset({ColumnType.FLOAT, ColumnType.LAT, ColumnType.LON})


@dataclass
class GenContext:
    seed: int
    file_rel: str
    registry: IdRegistry
    namespaces: dict[int, str]  # ID column index -> registry key
    settings: Any


def is_level_generated(p: ColumnProfile) -> bool:
    """Generated by exact quota over the real raw values."""
    if p.type in LEVEL_TYPES:
        return True
    if p.type is ColumnType.INTEGER and p.subtype == "discrete":
        return True
    return p.type is ColumnType.DIGIT_CODE and bool(p.params.get("levels_mode"))


def generate_values(p: ColumnProfile, model: ColumnModel, n: int, rng: np.random.Generator,
                    faker_factory: Any = None) -> tuple[np.ndarray, dict[str, bool]]:
    """``n`` rendered non-missing values for one column, plus adjustment flags."""
    t = p.type
    flags: dict[str, bool] = {}
    if n == 0:
        return np.empty(0, dtype=object), flags
    exact_extremes = not p.params.get("_no_exact_extremes", False)
    model = pseudonyms.generation_model(p, model)  # D35: pseudonymised units replaced by their pseudonyms
    if is_level_generated(p):
        if not model.nonmissing_counts:
            raise UnsupportedColumnError(f"column {p.name!r}: no values to sample")
        levels = list(model.nonmissing_counts)
        counts = list(model.nonmissing_counts.values())
        integer_like = t in (ColumnType.INTEGER, ColumnType.INTEGER_YEAR)
        values, adjusted = quota_sample(levels, counts, n, rng, floor=not integer_like)
        flags["rare_category_adjusted"] = adjusted
        if integer_like and exact_extremes:
            flags["extreme_value_adjusted"] = _ensure_level_extremes(values, levels, rng)
        return values, flags
    if t in _CONTINUOUS or (t is ColumnType.INTEGER and p.subtype == "continuous"):
        decimals = int(p.params.get("decimals", 0))
        if t is ColumnType.INTEGER:
            decimals = 0
        # values wider than float64 (int64 from 2**53, 16+ significant digits) on exact integers (R2-12)
        wide = numeric.generate_continuous_wide(p, model, n, rng, decimals, exact_extremes)
        y, adj = wide if wide is not None else numeric.generate_continuous(model, n, rng, decimals, exact_extremes)
        flags["extreme_value_adjusted"] = adj
        # R9-01: a real number that is a real person ID (an exact extreme, an interpolated value landing on it) is
        # redrawn from the column's distribution, never written
        return render_values(p, numeric.avoid_real_ids(p, model, y, rng)), flags
    if t is ColumnType.HIGH_CARD_CATEGORICAL:
        values, adjusted = text.invented_labels(p, model, n, rng)
        flags["rare_category_adjusted"] = adjusted
        return values, flags
    if t is ColumnType.FREE_TEXT:
        return text.lorem(p, model, n, rng), flags
    if t is ColumnType.DIGIT_CODE:
        return text.masked_codes(p, model, n, rng), flags
    if t in _PII_TYPES:
        values, f = pii.generate_pii(p, model, n, rng, faker_factory or (lambda: None))
        flags.update(f)
        return values, flags
    if t is ColumnType.MULTI_SELECT:
        values, f = text.generate_text_extended(p, model, n, rng)
        flags.update(f)
        return values, flags
    if TYPE_INFO[t].family == "date":
        if p.params.get("_sharing_person_date"):
            from .sharing_dates import generate_dates as generate_sharing_dates

            return generate_sharing_dates(p, model, n, rng)
        values, f = dates.generate_dates(p, model, n, rng)
        flags.update(f)
        return render_values(p, values), flags
    if t in _B_TYPES:
        values, f = numeric.generate_numeric_extended(p, model, n, rng)
        flags.update(f)
        return render_values(p, numeric.avoid_real_ids(p, model, values, rng)), flags  # R9-01, as above
    if t is ColumnType.EMPTY:
        raise UnsupportedColumnError(f"column {p.name!r}: EMPTY column with non-missing slots")
    raise UnsupportedColumnError(f"column {p.name!r}: {t.value} columns cannot be generated",
                                 fix=f"--null {p.name} or --exclude {p.name}")


def _ensure_level_extremes(values: np.ndarray, levels: list[Any], rng: np.random.Generator) -> bool:
    """D14 for discrete integers: the exact min and max raw values appear >= 1 time.

    Compared exactly (``Decimal``): float64 cannot tell int64 codes from ``2**53`` apart (R2-12).
    """
    nums = [numeric.exact_value(v) for v in levels]
    if any(x is None for x in nums):
        return False
    if len(levels) < 2 or len(values) < 2:
        return False
    lo = levels[min(range(len(nums)), key=nums.__getitem__)]
    hi = levels[max(range(len(nums)), key=nums.__getitem__)]
    adjusted = False
    for target in (lo, hi):
        if np.any(values == target):
            continue
        # replace one row of the most frequent other value (minimal distortion)
        uniq, cnt = np.unique(values.astype(str), return_counts=True)
        donor = uniq[int(np.argmax(cnt))]
        pos = np.flatnonzero(values.astype(str) == donor)
        values[int(rng.choice(pos))] = target
        adjusted = True
    return adjusted


def fill_missing(model: ColumnModel, m: int, rng: np.random.Generator) -> tuple[np.ndarray, bool]:
    """``m`` missing tokens by exact quota over the real tokens (floor >= 1 each)."""
    if m == 0:
        return np.empty(0, dtype=object), False
    if not model.missing_counts:
        out = np.empty(m, dtype=object)
        out[:] = ""
        return out, False
    return quota_sample(list(model.missing_counts), list(model.missing_counts.values()), m, rng)


def generate_independent(p: ColumnProfile, model: ColumnModel, n: int, rng: np.random.Generator,
                         faker_factory: Any = None,
                         miss: np.ndarray | None = None) -> tuple[np.ndarray, dict[str, bool]]:
    """A full column of ``n`` values - used for per-entity values.

    Missing slots are ``miss`` when given (the joint per-entity pattern, D6),
    else drawn by exact quota; either way >= 1 missing slot when the model has
    missing values (and >= 1 value when it has values) once ``n`` allows (D14).
    """
    n_nm, n_m = model.n_nonmissing, model.n_missing
    if n_nm + n_m == 0:
        out = np.empty(n, dtype=object)
        out[:] = ""
        return out, {}
    if miss is not None:
        miss = np.array(miss, dtype=bool)
        if n_m and n > 1 and not miss.any():
            miss[int(rng.integers(n))] = True  # floor: >= 1 missing when the source has any
        if n_nm and n > 1 and miss.all():
            miss[int(rng.integers(n))] = False  # floor: >= 1 value when the source has any
        m = int(miss.sum())
    else:
        alloc = largest_remainder([n_nm, n_m], n)
        m = int(alloc[1])
        if n_m and m == 0 and n > 1:
            m = 1  # floor: >= 1 missing when the source has any
        miss = np.zeros(n, dtype=bool)
        if m:
            miss[rng.choice(n, size=m, replace=False)] = True
    vals, flags = generate_values(p, model, n - m, rng, faker_factory)
    toks, adj = fill_missing(model, m, rng)
    out = np.empty(n, dtype=object)
    out[~miss] = vals
    out[miss] = toks
    if adj:
        flags["rare_category_adjusted"] = True
    return out, flags


def _inexact_rows_message(off: list[dict[str, Any]], column: str | None) -> Message:
    """R9-04: the warning for row counts that the ID blocks could not match exactly (counts only, no value): the
    file is WARN, never PASS, when a level's, NA token's or blank pattern's rows differ from the source's."""
    labels = sum(o["labels"] for o in off)
    rows = sum(o["rows"] for o in off)
    what = ("levels/NA tokens of this within-ID constant" if column is not None
            else "blank/non-blank patterns of the within-ID constants")
    return Message("warning", "entity_rows_inexact",
                   f"{labels} {what} could not get their exact source row counts ({rows} row(s) dealt elsewhere): no "
                   "exact deal of the values to the ID block sizes was found; entity counts are exact (D4)",
                   column=column)


def generate_table(tp: TableProfile, ctx: GenContext) -> SyntheticTable:
    """Assemble one synthetic table (see module docstring).

    Every value is drawn with the run's real phone and SSN keys active (``privacy.leaks.plan_digit_keys``,
    ``privacy.digits.guard``): no generator writes a real phone number or SSN of the run into a value, not even
    by chance through the digits it draws. So are the run's real texts that it never writes
    (``privacy.leaks.plan_real_texts``, ``privacy.texts.guard``; R7-01, R7-02): no generator writes a real text
    value of ANY column of the run (a name, a pseudonymised label, a value of an excluded column ...).
    """
    from .population import PLAN_KEY, generation_profile

    if (population := tp.private.extra.get(PLAN_KEY)) is not None:
        tp = generation_profile(tp, population)
    with digit_guard(tp.private.extra.get("run_digit_keys")), text_guard(tp.private.extra.get(TEXTS_KEY)), \
            id_guard(run_ids(tp)):
        return _generate_table(tp, ctx)


def _generate_table(tp: TableProfile, ctx: GenContext) -> SyntheticTable:
    n = tp.n_rows
    rf = RngFactory(ctx.seed, ctx.file_rel, tp.name)
    cols: dict[int, np.ndarray] = {}
    flags: dict[int, dict[str, bool]] = {}
    profiles = {p.index: p for p in tp.columns}
    population = tp.private.extra.get("_sharing_population")

    def faker_factory_for(p: ColumnProfile) -> Any:
        return lambda: faker_for(ctx.seed, ctx.file_rel, tp.name or "", p.index, p.name, "faker")

    # 0. same-shape pseudonyms for the real text units the D35 allowlist did not keep: the run's one map (or one
    # map for the table when it is generated on its own)
    pseudonyms.build_maps(tp, rf.table_stream("pseudonyms"))
    # 1. IDs
    for i in tp.entity.id_columns:
        cols[i] = (population.id_values[i].copy() if population is not None else
                   ctx.registry.render(ctx.namespaces[i], tp.private.id_raw[i]))
    mm = tp.structure.missingness
    groups = None  # each row's entity-pattern group (couples the row-level patterns to the entity ones)
    messages_early: list[Message] = []  # R9-04: row counts the ID blocks could not match exactly
    # 2. within-ID constants: joint blank/non-blank pattern per entity (D6), then one value per entity (D4)
    if tp.entity.constant_columns and tp.private.entity_index is not None:
        # rows of each synthetic entity = its real ID's block (D8): patterns and values are dealt so their row
        # counts stay as in the source, not only their entity counts (R2-10)
        sizes = np.bincount(tp.private.entity_index, minlength=tp.entity.n_entities)[:tp.entity.n_entities]
        min_cell = int(getattr(ctx.settings, "min_cell", 1) or 1)
        off: list[dict[str, Any]] = []  # R9-04: blank/non-blank pattern rows the ID blocks could not match exactly
        ecodes, emask = structure.sample_entity_mask(mm, tp.entity.n_entities, rf.table_stream("entity_missingness"),
                                                     sizes=None if population is not None else sizes,
                                                     min_entities=min_cell, report=off)
        if off:
            messages_early.append(_inexact_rows_message(off, None))
        ecol = {c: j for j, c in enumerate(mm.entity_columns)}
        if ecodes is not None and mm.cross is not None:
            groups = ecodes[tp.private.entity_index]
        real_values = (tp.private.extra.get("entity_values") or {}) if population is None else {}
        for i in tp.entity.constant_columns:
            p = profiles[i]
            emodel = tp.private.entity_models[i]
            ev, f = generate_independent(p, emodel, tp.entity.n_entities,
                                         rf.column(i, p.name, "entity"), faker_factory_for(p),
                                         miss=emask[:, ecol[i]] if i in ecol and ecodes is not None else None)
            row_counts = emodel.extra.get("_row_counts")
            written = pseudonyms.level_map(p)
            if row_counts:  # rows per value, keyed by the values written (D35: pseudonyms for pseudonymised ones)
                row_counts = pseudonyms.mapped_counts(row_counts, written)
            # a pseudonym writes no real value: it keeps its level's rows however few IDs hold it (R7-06)
            fakes = frozenset(written.values())
            # R9-04: each source ID's value as written (PRIVATE, in memory only) proves an exact deal of the values to
            # the ID blocks exists; per-level rows that still miss the source's are reported (a WARN, never a PASS)
            real_ev = real_values.get(i)
            witness = None
            if real_ev is not None and len(real_ev) == len(ev):
                witness = np.asarray([written.get(v, v) for v in real_ev.tolist()], dtype=object)
            off = []
            if population is None:
                ev = structure.balance_entity_values(ev, sizes, row_counts, emodel.missing_counts,
                                                     is_level_generated(p), rf.column(i, p.name, "entity_rows"),
                                                     min_cell, fakes, witness=witness, report=off)
            if population is None and emodel.extra.get("_row_bins"):  # numbers/dates: source value/block coupling
                ev = structure.balance_entity_numbers(ev, sizes, emodel.extra["_row_bins"], p,
                                                      rf.column(i, p.name, "entity_bins"),
                                                      row_counts, min_cell, fakes, report=off)
            if off:
                messages_early.append(_inexact_rows_message(off, p.name))
            if emodel.extra.get("floored_levels"):
                f["rare_category_adjusted"] = True
            if emodel.extra.get("floored_extremes"):
                f["extreme_value_adjusted"] = True  # a row-level min/max kept (profile.table.floor_entity_extremes)
            cols[i] = ev[tp.private.entity_index]
            flags[i] = f
    # 3. missingness patterns of the row-level columns (dealt to the entity patterns' rows when coupled)
    mask = structure.sample_missing_mask(mm, n, rf.table_stream("missingness"), groups=groups)
    # 4. independent columns
    for j, i in enumerate(mm.columns):
        p = profiles[i]
        miss = mask[:, j]
        m = int(miss.sum())
        rng = rf.column(i, p.name)
        vals, f = generate_values(p, p.model, n - m, rng, faker_factory_for(p))
        toks, adj = fill_missing(p.model, m, rf.column(i, p.name, "missing"))
        out = np.empty(n, dtype=object)
        out[~miss] = vals
        out[miss] = toks
        if adj:
            f["rare_category_adjusted"] = True
        cols[i] = out
        flags[i] = f
    for p in tp.columns:
        if p.role == "null":
            out = np.empty(n, dtype=object)
            out[:] = None
            cols[p.index] = out
    # 4b. no real person's full name (full-name values; first/middle + last parts), run-wide (R1-04)
    messages: list[Message] = messages_early + pii.avoid_real_full_names(tp, cols, rf.table_stream("names"))
    # 5. structural switches (AREA D)
    messages += list(structure.apply_structure(
        tp, cols, lambda purpose: rf.table_stream("structure:" + purpose), ctx.settings))
    # 6. D35 (R8-05): an --na-value token the allowlist did not keep is written as its pseudonym, whatever path wrote it
    for p in tp.columns:
        if p.index in cols and p.role != "null":
            cols[p.index] = pseudonyms.apply_na_map(p, cols[p.index])

    out_cols: list[SyntheticColumn] = []
    for p in tp.columns:
        if p.role == "excluded":
            continue
        f = flags.get(p.index, {})
        for k, v in f.items():
            if v:
                p.flags[k] = True
        out_cols.append(SyntheticColumn(p.index, p.name, cols[p.index], flags=dict(f)))
    header = [p.name for p in tp.columns if p.role != "excluded"]
    return SyntheticTable(tp.name, header, n, out_cols, tp, messages=messages)
