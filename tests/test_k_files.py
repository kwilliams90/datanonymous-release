def _run(src: Path, tmp: Path, *extra: str, name: str = "run"):
    out, rep = tmp / f"{name}_out", tmp / f"{name}_rep"
    res = run_cli(src, "--out-dir", out, "--report-dir", rep, "--seed", SEED, *extra)
    return res, out, rep


def _entry(rep: Path, source: str) -> dict:
    return next(f for f in json.loads((rep / "report.json").read_text(encoding="utf-8"))["files"]
                if f["source"] == source)


def _texts(*dirs: Path) -> str:
    out = []
    for d in dirs:
        for p in sorted(d.rglob("*")):
            if p.is_file():
                out.append(p.read_bytes().decode("utf-8", "replace"))
    return "\n".join(out)


def _columns(rep: Path, name: str) -> dict[str, dict]:
    data = json.loads((rep / "files" / f"{name}.json").read_text(encoding="utf-8"))
    return {c["name"]: c for c in data["tables"][0]["columns"]}


# =========================================================================== K-14 ISO date cells in General format
def _iso_book(path: Path, with_time: bool = False, title: bool = False, mixed: bool = False) -> Path:
    wb = Workbook(iso_dates=True)
    ws = wb.active
    ws.title = "S"
    if title:
        ws.append(["Enrollment snapshot"])
        c = ws.cell(row=1, column=2, value=dt.datetime(2024, 9, 3))
        c.number_format = "General"
    ws.append(["event_date", "n"])
    rng = random.Random(14)
    for i in range(40):
        d = dt.datetime(2024, 1, 1) + dt.timedelta(days=rng.randint(0, 300),
                                                    hours=rng.randint(7, 15) if with_time else 0)
        ws.append([d, rng.randint(1, 9)])
        c = ws.cell(row=ws.max_row, column=1)
        c.number_format = "yyyy-mm-dd" if mixed and i % 2 else "General"
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


_CELL_RE = re.compile(r'<c r="A(\d+)"([^>]*)>')


def _date_cells(path: Path) -> Counter:
    """(stored as, number format) of the event_date cells: 'iso' = ISO text (t="d"), 'serial' = a number."""
    with zipfile.ZipFile(path) as z:
        xml = z.read("xl/worksheets/sheet1.xml").decode()
    attrs = {int(m.group(1)): m.group(2) for m in _CELL_RE.finditer(xml)}
    ws = load_workbook(path)["S"]
    head = next(r for r in range(1, 4) if ws.cell(row=r, column=1).value == "event_date")
    out: Counter = Counter()
    for r in range(head + 1, ws.max_row + 1):
        c = ws.cell(row=r, column=1)
        assert isinstance(c.value, (dt.date, dt.datetime)), (r, c.value)
        out[("iso" if 't="d"' in attrs[r] else "serial", c.number_format)] += 1
    return out


@pytest.mark.parametrize("with_time", [False, True])
def test_k14_iso_general_dates_pass_and_stay_iso_general(tmp_path: Path, with_time: bool) -> None:
    src = _iso_book(tmp_path / "in" / "iso.xlsx", with_time=with_time)
    res, out, rep = _run(src.parent, tmp_path)
    assert res.exit_code == 0, res.output
    assert _entry(rep, "iso.xlsx")["status"] in ("PASS", "WARN")
    assert _date_cells(out / "iso.xlsx") == Counter({("iso", "General"): 40})
    assert _columns(rep, "iso.xlsx")["event_date"]["type"] in ("DATE", "DATETIME")


def test_k14_title_cells_and_mixed_formats(tmp_path: Path) -> None:
    """A column mixing ISO General cells and serial yyyy-mm-dd cells keeps both by exact quota; a General date cell
    in a title row stays an ISO General date cell too (a placeholder date)."""
