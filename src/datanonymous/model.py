@dataclass
class Message:
    """A finding shown in ``inspect``, the console summary and the report.

    ``level`` is 'info' | 'warning' | 'error'. A file with any 'warning' is WARN;
    any 'error' is FAIL. ``text`` must be report-safe (no real non-label values).
    """

    level: str
    code: str
    text: str
    column: str | None = None
    fix: str | None = None

    def to_public(self) -> dict[str, Any]:
        out: dict[str, Any] = {"level": self.level, "code": self.code, "text": self.text}
        if self.column is not None:
            out["column"] = self.column
        if self.fix:
            out["fix"] = self.fix
        return out


